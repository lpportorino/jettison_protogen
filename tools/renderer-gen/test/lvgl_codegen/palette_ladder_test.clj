(deftest test-the-shipped-disabled-tones-are-not-on-their-own-stated-line
  ;; NOT A CANARY - a pinned MEASUREMENT, and one that is allowed to be retired.
  ;; tokens.edn states each tone was solved as the dimmest OKLCH lightness at a
  ;; named source's own hue and chroma. Under this namespace's OKLCH<->sRGB path
  ;; neither result is emittable on that line at all, so the two derivations
  ;; disagree at the resolution the palette is written in. Whatever produced the
  ;; shipped values is not in this tree, so which path stepped off the line
  ;; cannot be settled here. If this test goes GREEN the disagreement is gone and
  ;; the paragraph in `preferences` should be deleted with it.
  (testing "the shipped tone is absent from the emittable colours on its stated line"
    (doseq [{:keys [label source shipped on-line-neighbour]} hand-derived-tones]
      (let [base (pl/hex->oklch source)
            line (set (map :hex (pl/candidates {:oklch-c (:oklch-c base)
                                                :oklch-h (:oklch-h base)})))]
        (is (not (contains? line shipped))
            (str label ": " shipped " IS emittable at " source
                 "'s hue and chroma after all - the disagreement this test"
                 " records has been resolved, and the claim in `preferences`"
                 " must be deleted rather than kept"))
        (is (contains? line on-line-neighbour)
            (str label ": " on-line-neighbour " is not on the line either,"
                 " so this test no longer measures what it claims")))))
  (testing "and the rule tokens.edn states picks the neighbour, one 8-bit level away"
    (doseq [{:keys [label source reference on-line-neighbour]} hand-derived-tones]
