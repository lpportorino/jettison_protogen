// Theme regression: the child-theme contract (vanilla idempotency +
// button geometry)
// ═══════════════════════════════════════════════════════════════════

mod theme_regression {
    use super::*;
    /// VANILLA (family 1) restates stock values over the exact targets the
    /// asgard family styles, so rendering under it must be BIT-IDENTICAL to
    /// STOCK (family 2, child apply skipped) — for EVERY fixture. This is
    /// the per-card idempotency gate: a vanilla arm that drifts from the
    /// stock formula it mirrors splits the hash on the fixture exercising
    /// that widget, naming the drift precisely.
    #[test]
    fn vanilla_equals_stock_for_every_fixture() {
        let mut names: Vec<String> = std::fs::read_dir(fixtures_dir())
            .expect("fixtures dir")
            .filter_map(|entry| {
                let path = entry.expect("dir entry").path();
                (path.extension().is_some_and(|ext| ext == "pb")).then(|| {
                    path.file_stem()
                        .expect("stem")
                        .to_string_lossy()
                        .into_owned()
                })
            })
            // Screens only: the fixture generator also leaves
            // `<screen>.patch.pb` tree-patch artifacts beside the screens
            // whenever a prior run's baseline exists and the IR moved. A
            // patch is a DIFFERENT message type — loading one as a screen
            // is a guaranteed decode failure, not a theme comparison.
            .filter(|name: &String| !name.ends_with(".patch"))
            .collect();
        names.sort();
        // Vacuous-input guard: an empty enumeration must FAIL, not pass over
        // nothing (the fixture generator emits 100+ .pb screens today).
        assert!(
            names.len() >= 50,
            "fixture enumeration collapsed to {} .pb files",
            names.len()
        );
        for name in &names {
            let render_family = |family: i32| {
                let mut host = new_host_with_wasi();
                host.set_theme_family(family).expect("set_theme_family");
                render(&mut host, name)
            };
            let vanilla = render_family(1);
            let stock = render_family(2);
            assert_identical(&format!("{name}: vanilla(1) vs stock(2)"), &vanilla, &stock);
        }
    }
    /// The themed default button keeps its label fully visible and centered:
    /// the label bbox sits inside the button bbox, the dump carries no
    /// `vis_px` (emitted only when a node is partially clipped/occluded),
    /// and the centers agree within 2px on both axes — the "tight control
    /// padding must not eat the label" contract.
    #[test]
    fn button_label_unclipped_and_centered() {
        let mut host = new_host();
        let fb = render(&mut host, "vr_button_unstyled");
        assert_not_empty("themed button", &fb);
        let root = tree(&mut host);
        let (btn, label) =
            find_button_with_label(&root).expect("button + label in vr_button_unstyled");
        let (bx0, by0, bx1, by1) = coords(&btn);
        let (lx0, ly0, lx1, ly1) = coords(&label);
        assert!(
            lx0 >= bx0 && ly0 >= by0 && lx1 <= bx1 && ly1 <= by1,
            "label ({lx0},{ly0})-({lx1},{ly1}) escapes button ({bx0},{by0})-({bx1},{by1})"
        );
        assert!(
            label.get("vis_px").is_none(),
            "label is partially clipped/occluded: vis_px={:?}",
            label["vis_px"]
        );
        let (bcx, bcy) = ((bx0 + bx1) / 2, (by0 + by1) / 2);
        let (lcx, lcy) = ((lx0 + lx1) / 2, (ly0 + ly1) / 2);
        assert!(
            (bcx - lcx).abs() <= 2 && (bcy - lcy).abs() <= 2,
            "label center ({lcx},{lcy}) off button center ({bcx},{bcy}) by more than 2px"
        );
    }
    /// The button's corner radius stays SMALL (control tier), never the
    /// stock pill: 6px in from a corner at 2px below the top edge must be
    /// button-fill (equal to the center pixel). A pill radius (>= half the
    /// button height, the stock look on small chips) leaves those insets as
    /// background and fails.
    #[test]
    fn button_corners_are_filled_not_pill() {
        let mut host = new_host();
        let fb = render(&mut host, "vr_button_unstyled");
        let root = tree(&mut host);
        let (btn, _) = find_button_with_label(&root).expect("button in vr_button_unstyled");
        let (x0, y0, x1, y1) = coords(&btn);
        // Fill reference: mid-height left inset — always fill even for a
        // pill (widest at mid-height), and never a label glyph (the center
        // pixel IS one).
        let center = px(&fb, x0 + 6, (y0 + y1) / 2);
        for (cx, cy, corner) in [
            (x0 + 6, y0 + 2, "top-left"),
            (x1 - 6, y0 + 2, "top-right"),
            (x0 + 6, y1 - 2, "bottom-left"),
            (x1 - 6, y1 - 2, "bottom-right"),
        ] {
            assert_eq!(
                px(&fb, cx, cy),
                center,
                "{corner} corner inset ({cx},{cy}) is not button fill — pill-radius regression"
            );
        }
    }
    /// RGBA pixel at (x, y).
    fn px(fb: &[u8], x: i32, y: i32) -> [u8; 4] {
        let idx = usize::try_from(y * WIDTH as i32 + x).expect("in-bounds pixel") * 4;
        fb[idx..idx + 4].try_into().expect("4-byte pixel")
    }
    /// (x1, y1, x2, y2) of a dumped node.
    fn coords(node: &serde_json::Value) -> (i32, i32, i32, i32) {
        let c = node["coords"].as_array().expect("coords");
        let v = |i: usize| i32::try_from(c[i].as_i64().expect("coord")).expect("i32 coord");
        (v(0), v(1), v(2), v(3))
    }
    /// First lv_button in the tree plus the first lv_label inside it.
    fn find_button_with_label(
        root: &serde_json::Value,
    ) -> Option<(serde_json::Value, serde_json::Value)> {
        fn find_label(node: &serde_json::Value) -> Option<serde_json::Value> {
            if node["type"] == "lv_label" {
                return Some(node.clone());
            }
            node["children"].as_array()?.iter().find_map(find_label)
        }
        fn walk(node: &serde_json::Value) -> Option<(serde_json::Value, serde_json::Value)> {
            if node["type"] == "lv_button" {
                if let Some(label) = find_label(node) {
                    return Some((node.clone(), label));
                }
            }
            node["children"].as_array()?.iter().find_map(walk)
        }
        walk(root)
    }
}
