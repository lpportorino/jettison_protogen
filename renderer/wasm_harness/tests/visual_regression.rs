    /// an lv_slider at a fraction of its track (widget_center only gives the
    /// midpoint; the cmd_by_value index tests need the left/right thirds).
    fn widget_coords(host: &mut ControlsHost, wtype: &str) -> (i32, i32, i32, i32) {
        fn find<'a>(node: &'a serde_json::Value, wtype: &str) -> Option<&'a serde_json::Value> {
            if node["type"] == wtype {
                return Some(node);
            }
            node["children"]
                .as_array()?
                .iter()
                .find_map(|child| find(child, wtype))
        }
        let root = tree(host);
        let node = find(&root, wtype).unwrap_or_else(|| panic!("no {wtype} in tree"));
        let coords = node["coords"].as_array().expect("coords");
        let v = |i: usize| coords[i].as_i64().expect("coord") as i32;
        (v(0), v(1), v(2), v(3))
    }
