// Breakpoint matrix: vr_bp_matrix exercises the NON-color responsive
// axes — width (64→96→128→160), padding (xs→sm→md→xl) and font
// (12→16→22→32) per tier. The tier box reuses vr_bp_color's color
// progression solely so each tier can be LOCATED and MEASURED.
// ═══════════════════════════════════════════════════════════════════

mod breakpoint_matrix {
    use super::*;
    /// Tier color (locator) + expected tier-box width in px.
    fn tier(bp: i32) -> ((u8, u8, u8), u32) {
        match bp {
            0 => (RED, 64),
            1 => (AMBER, 96),
            2 => (GREEN, 128),
            3 => (ACCENT_DARK, 160),
            _ => panic!("invalid bp {bp}"),
        }
    }
    #[test]
    fn tier_box_width_tracks_breakpoint() {
        let mut host = new_host();
        for bp in 0..4 {
            let (color, expected_width) = tier(bp);
            let fb = render_fixture(&mut host, "vr_bp_matrix", bp, DEFAULT_THEME);
            let regions = analysis::find_color_regions(&fb, WIDTH, HEIGHT, color, COLOR_TOLERANCE);
            assert!(!regions.is_empty(), "bp{bp}: tier box not found by color");
            let bbox = &regions[0].bbox;
            assert!(
                bbox.w.abs_diff(expected_width) <= SIZE_TOLERANCE,
                "bp{bp}: tier box width {} ≉ expected {expected_width}",
                bbox.w
            );
        }
    }
    /// Padding + font tiers also restyle: every pair of breakpoints
    /// renders differently (width alone is asserted above; this catches
    /// a tier whose padding/font tokens silently stop applying).
    #[test]
    fn every_tier_restyles_the_screen() {
        let mut host = new_host();
        let frames: Vec<Vec<u8>> = (0..4)
            .map(|bp| render_fixture(&mut host, "vr_bp_matrix", bp, DEFAULT_THEME))
            .collect();
        for i in 0..frames.len() {
            for j in (i + 1)..frames.len() {
                assert_differ(
                    &format!("vr_bp_matrix bp{i} vs bp{j}"),
                    &frames[i],
                    &frames[j],
                    MIN_DIFF_RATIO,
                );
            }
        }
    }
    /// Live transition: switching the breakpoint WITHOUT reloading the UI
    /// must re-apply the tier styles (composite-index rebuild) — the
    /// browser harness's bp dropdown depends on exactly this path.
    #[test]
    fn live_breakpoint_switch_resizes_tier_box() {
        let mut host = new_host();
        let _ = render_fixture(&mut host, "vr_bp_matrix", 0, DEFAULT_THEME);
        host.set_breakpoint(3).expect("set_breakpoint");
        let mut changed_any = false;
        for _ in 0..RENDER_TICKS {
            if host.tick(TICK_MS).expect("tick") {
                changed_any = true;
            }
        }
        assert!(changed_any, "no flush within the pinned ticks");
        let fb = host.read_framebuffer().expect("framebuffer");
        let (color, expected_width) = tier(3);
        let regions = analysis::find_color_regions(&fb, WIDTH, HEIGHT, color, COLOR_TOLERANCE);
        assert!(
            !regions.is_empty(),
            "xl tier box not found after live switch"
        );
        assert!(
            regions[0].bbox.w.abs_diff(expected_width) <= SIZE_TOLERANCE,
            "xl tier box width {} ≉ {expected_width} after live switch",
            regions[0].bbox.w
        );
    }
}
