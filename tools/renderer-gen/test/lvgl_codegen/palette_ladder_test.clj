      (is (= #{:fg-0} (set (map :reference (:blocked-by f))))
          "fg-1's block is not attributed to fg-0")))
  (testing "and it is genuinely upstream: removing the upstream cause changes the status"
    ;; Dark only. In light mode fg-0 conflicts for its own reasons, so fg-1/light
    ;; stays blocked there and would prove nothing about the attribution.
    (is (= :reference-conflict (:status (finding-for ladder-proposal :fg-1 :dark)))
        (str "fg-1/dark does not become judgeable when the status fills are"
             " dropped, so :blocked-upstream was not attributable to them"))))

(deftest test-reference-conflict-names-the-constraints-to-drop
  ;; REVERT-TO-BREAK: in `solve-cell`, drop the constraints by MAP IDENTITY
  ;; instead of by index —
  ;;   `dropped (mapv #(nth active %) (remove (set keep-idx) (range (count active))))`
  ;;   -> `dropped (let [kept (set (map #(first (nth active %)) keep-idx))]
  ;;                 (filterv (fn [[c _]] (not (contains? kept c))) active))`
  ;; CONTROL: test-reference-infeasible-fires-and-names-the-upstream-role stays
  ;; GREEN.
  ;;
  ;; THE FIRST MUTATION WRITTEN HERE WAS A NO-OP and the suite stayed green under
  ;; it, which is the only reason this comment is exact: `active` holds
  ;; (constraint, mode) PAIRS, and those are distinct even for a mode-invariant
  ;; role, so a set difference over PAIRS is correct. The defect needs the mode
  ;; STRIPPED first — which is what the code did before this test existed, and
  ;; why status-warning reported a droppable count with an empty drop list.
  (testing "a conflict names which constraints must move, not just how many"
    (let [f (finding-for derive-proposal :status-warning :dark)]
      (is (= :reference-conflict (:status f)))
