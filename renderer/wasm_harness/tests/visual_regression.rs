    /// Center of the first widget of `wtype` whose subtree contains a label
    /// with exactly `label` as its text (e.g. the "Status" tab button).
    fn widget_center_by_label(host: &mut ControlsHost, wtype: &str, label: &str) -> (i32, i32) {
        fn has_label(node: &serde_json::Value, label: &str) -> bool {
            if node["type"] == "lv_label" && node["text"] == label {
                return true;
            }
            node["children"]
                .as_array()
                .is_some_and(|children| children.iter().any(|child| has_label(child, label)))
        }
        fn find<'a>(
            node: &'a serde_json::Value,
            wtype: &str,
            label: &str,
        ) -> Option<&'a serde_json::Value> {
            if node["type"] == wtype && has_label(node, label) {
                return Some(node);
            }
            node["children"]
                .as_array()?
                .iter()
                .find_map(|child| find(child, wtype, label))
        }
        let root = tree(host);
        let node = find(&root, wtype, label)
            .unwrap_or_else(|| panic!("no {wtype} containing label {label:?} in tree"));
        let coords = node["coords"].as_array().expect("coords");
        let value = |i: usize| coords[i].as_i64().expect("coord") as i32;
        ((value(0) + value(2)) / 2, (value(1) + value(3)) / 2)
    }
