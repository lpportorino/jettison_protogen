#[test]
fn resize_rejects_overflowing_dimension_and_stays_renderable() {
    let mut host = new_host();
    // A valid resize is accepted.
    assert_eq!(host.resize_raw(800, 600).expect("resize call"), 0);
    // 32768 = 2^15, so 32768 * 32768 * 4 = 2^32, which WRAPS TO 0 in the uint32
    // `width * height * 4` size computation. The old (uncapped) path calloc'd a
    // zero/tiny buffer and returned 0 (success) — then rendered past it. The
    // dimension cap must REJECT it (-1) instead of silently corrupting the heap.
    assert_eq!(
        host.resize_raw(32_768, 32_768).expect("resize call"),
        -1,
        "an overflow-to-zero dimension must be rejected, not accepted with a tiny buffer"
    );
    // Just over the 16384 cap is rejected too (before any allocation).
    assert_eq!(host.resize_raw(16_385, 100).expect("resize call"), -1);
    // The display survived every rejected resize — a tick still renders. NOTE:
    // this covers the dimension CAP (reject) and the resize SUCCESS path (the
    // 400→800 realloc+swap above). It does NOT cover the allocate-before-free
    // UAF path (an alloc FAILURE after the cap passes) — inducing a wasm malloc
    // failure needs an allocator hook the harness has no seam for; that fix is
    // verified by inspection.
    host.tick(TICK_MS).expect("tick after rejected resizes");
}
#[test]
fn controls_destroy_double_call_is_idempotent() {
    // The 2026-07-19 livelock class: a second consecutive controls_destroy
    // used to read lv_screen_active() off the NULLed display — wasm
    // offset-0 garbage, a cyclic LVGL list walk, an unbounded spin. The
    // wasm-side guard must make re-entry a loud no-op (rc 0). On a
    // regressed wasm this test HANGS the suite — deliberately loud.
    // (Host Drop is guarded separately; explicit destroy() always reaches
    // the guest so this test genuinely exercises the wasm contract.)
    let mut host = new_host();
    let fb = render(&mut host, "vr_bare");
    assert_not_empty("pre-destroy render", &fb);
    host.destroy().expect("first destroy");
    host.destroy()
        .expect("second destroy must be an idempotent no-op (rc 0)");
}
