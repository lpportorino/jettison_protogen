    /// gesture-end path), but PRESS_LOST itself is NOT synthesizable
    /// through the public controls ABI: the glass carries PRESS_LOCK, so
    /// the indev never re-searches mid-press (verified in lv_indev.c —
    /// the only PRESS_LOST sites need a re-search or the module-internal
    /// lv_indev_wait_release; deletion sends INDEV_RESET instead). This
