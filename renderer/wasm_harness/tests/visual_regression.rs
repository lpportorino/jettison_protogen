// host_event envelope: the named-event lane (ABI v2). An EventBinding
// with a nonempty `name` whose host-relay gate is open (no subject
// mutation, or notify_host) emits the CLOSED JSON envelope
// {"v":1,"tag":name,"origin":uid,"event":trigger,"seq":n,"value":int}
// via env.host_event — ADDITIVE beside the cmd.* template wire, whose
// bytes stay untouched. Screens are prost-built (boundary_contracts
// style) so hostile names and minimal bindings need no fixture codegen;
// the ride-beside case reuses the REAL vr_event_notify fixture.
