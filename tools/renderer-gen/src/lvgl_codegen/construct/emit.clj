(ns lvgl-codegen.construct.emit
  "Emitters: hydrated IR construct → target text
   (`docs/lvgl-factory/03-FACTORY-DESIGN.md`, build step 4). Pure data→string; the
   generated `.proto` is fed through `buf format` then `tools/proto-sync.sh`
   (nanopb/java/pronto), so this emitter favours a deterministic, diffable shape
   over hand-formatting — `buf format` owns the final layout.

   This is the enum slice. Struct/message emission + the `.options` follow."
  (:require [camel-snake-kebab.core :as csk]
            [clojure.string :as str]
            [lvgl-codegen.construct.schema :as schema]
            [malli.core :as m]))

(set! *warn-on-reflection* true)

(defn enum->proto
  "Emit a proto3 `enum` block from an `:enum` construct. Members are emitted in
   IR order with their assign-once numbers; for the direct-cast set those numbers
   equal the LVGL value (the parity contract)."
  [{:keys [proto-type members]}]
  (str "enum "
       proto-type
       " {\n"
       (str/join "\n"
                 (for [{:keys [proto-name proto-number]} members]
                   (str "  " proto-name " = " proto-number ";")))
       "\n}\n"))
(m/=> enum->proto [:=> [:cat schema/enum-construct] [:string {:min 1}]])

(defn enum->keyword-map
  "The authoring-layer Clojure binding for one enum: `{:clj-keyword
   proto-number}` (e.g. `{:center 9, …}`) — what replaces the hand-written
   `emit_proto` keyword→int maps at the O2 cutover."
  [{:keys [members]}]
  (into {} (map (juxt :clj-keyword :proto-number)) members))
(m/=> enum->keyword-map
      [:=> [:cat schema/enum-construct] [:map-of :keyword [:int {:min 0}]]])

(defn enum->keyword-member-map
  "The authoring→proto-member binding for one enum: `{:clj-keyword
   :PROTO_NAME}` (e.g. `{:symmetrical :BAR_MODE_SYMMETRICAL}`) — what
   emit-proto translates authoring keywords in `*_props` maps through; the
   proto-IR layer carries the member spellings."
  [{:keys [members]}]
  (into {} (map (juxt :clj-keyword (comp keyword :proto-name))) members))
(m/=> enum->keyword-member-map
      [:=> [:cat schema/enum-construct] [:map-of :keyword :keyword]])

(defn enum->lvgl-keyword-map
  "The authoring binding for an AUTHORING-ONLY enum: `{:clj-keyword
   resolved-int}` — raw LVGL header values (probe-resolved), never registry
   numbers; these never appear as proto enums."
  [{:keys [members]}]
  (into {} (map (juxt :clj-keyword :resolved-int)) members))
(m/=> enum->lvgl-keyword-map [:=> [:cat schema/enum-construct] [:map-of :keyword :int]])

(defn enum->malli-enum
  "The Malli schema for one enum: `[:enum :ALIGN_DEFAULT …]` over the
   keywordized proto member names — what replaces the hand-written
   `proto_schema` enum defs at the O2 cutover."
  [{:keys [members]}]
  (into [:enum] (map (comp keyword :proto-name)) members))
(m/=> enum->malli-enum [:=> [:cat schema/enum-construct] [:cat [:= :enum] [:+ :keyword]]])

(defn- lut-entry
  "One C array entry: the LVGL constant NAME (compile-time-checked against the
   live header — an upstream rename breaks the build loudly, never silently),
   or a literal 0 for a proto-only synthetic member."
  [{:keys [c-name proto-name proto-number]}]
  (str "  "
       (or c-name "0")
       ", /* "
       proto-number
       ": "
       proto-name
       (when-not c-name " (proto-only, no LVGL counterpart)")
       " */"))
(m/=> lut-entry [:=> [:cat schema/enum-member] [:string {:min 1}]])

(defn enum->c-lut
  "Emit the proto→LVGL C lookup table for one `:lut` enum: a `static const`
   array indexed by proto wire number. Throws unless the stamped numbers are
   contiguous 0..N-1 — a gap would silently misalign the array."
  [{:keys [typedef-name proto-type members]}]
  (let [root (csk/->snake_case_string proto-type)
        sorted (sort-by :proto-number members)
        numbers (mapv :proto-number sorted)]
    (when-not (= numbers (vec (range (count sorted))))
      (throw (ex-info "LUT numbering is not contiguous from 0"
                      {:proto-type proto-type :numbers numbers})))
    (str "/* "
         proto-type
         " proto enum -> LVGL "
         typedef-name
         " value (indexed by wire number). */\n"
         "static const "
         typedef-name
         " "
         root
         "_lut[] = {\n"
         (str/join "\n" (map lut-entry sorted))
         "\n};\n"
         "#define "
         (str/upper-case root)
         "_LUT_SIZE \\\n"
         "  (sizeof ("
         root
         "_lut) / sizeof ("
         root
         "_lut[0]))\n")))
(m/=> enum->c-lut [:=> [:cat schema/enum-construct] [:string {:min 1}]])

(defn luts->header
  "Assemble every `:lut` enum's table into the generated C header (include
   AFTER lvgl.h — the entries are LVGL constant names)."
  [enums]
  (str "/* GENERATED by lvgl-codegen.construct.factory — DO NOT EDIT.\n"
       " * Proto :lut enum -> LVGL value tables, indexed by proto wire number\n"
       " * (assign-once registry). Include AFTER lvgl.h.\n"
       " *\n"
       " * NO REGENERATION PATH EXISTS IN THIS TREE, and that is the honest\n"
       " * status rather than a missing command: factory/generate-luts! takes\n"
       " * extracted-enum EDN, and nothing here produces it. So this file is a\n"
       " * committed projection whose freshness nothing asserts. Restoring the\n"
       " * extractor is what would retire this note -- and it must land WITH a\n"
       " * byte-compare freshness lane (renderer.mk `manifests` is the shape:\n"
       " * emit to a temp dir, cmp, FATAL on drift). */\n"
       "#ifndef UI_LUTS_H\n#define UI_LUTS_H\n\n"
       (str/join "\n" (map enum->c-lut (filter #(= :lut (:cast-class %)) enums)))
       "\n#endif /* UI_LUTS_H */\n"))
(m/=> luts->header [:=> [:cat [:vector schema/enum-construct]] [:string {:min 1}]])

(defn- keyword-map-def
  "One `(def <root>-keyword->int {…})` source block, entries in wire order."
  [{:keys [proto-type] :as construct}]
  (let [root (csk/->kebab-case-string proto-type)
        entries (sort-by (juxt val key) (enum->keyword-map construct))]
    (str "(def "
         root
         "-keyword->int\n"
         "  \""
         proto-type
         " authoring keywords → proto wire ints.\"\n"
         "  {"
         (str/join "\n   " (map (fn [[k v]] (str k " " v)) entries))
         "})\n")))
(m/=> keyword-map-def [:=> [:cat schema/enum-construct] [:string {:min 1}]])

(defn- authoring-keyword-map-def
  "One authoring-only `(def <root>-keyword->int {…})` source block: raw LVGL
   header values, entries in value order."
  [{:keys [proto-type typedef-name] :as construct}]
  (let [root (csk/->kebab-case-string proto-type)
        entries (sort-by (juxt val key) (enum->lvgl-keyword-map construct))]
    (str "(def "
         root
         "-keyword->int\n"
         "  \""
         typedef-name
         " authoring keywords → LVGL header values"
         " (authoring-only:\n"
         "   OR'd onto the wire by emit-proto; no proto enum, no registry"
         " numbering).\"\n"
         "  {"
         (str/join "\n   " (map (fn [[k v]] (str k " " v)) entries))
         "})\n")))
(m/=> authoring-keyword-map-def [:=> [:cat schema/enum-construct] [:string {:min 1}]])

(defn- keyword-member-map-def
  "One `(def <root>-keyword->member {…})` source block, entries in wire
   order."
  [{:keys [proto-type members]}]
  (let [root (csk/->kebab-case-string proto-type)
        sorted (sort-by :proto-number members)]
    (str "(def "
         root
         "-keyword->member\n"
         "  \""
         proto-type
         " authoring keywords → proto member names.\"\n"
         "  {"
         (str/join "\n   "
                   (map (fn [{:keys [clj-keyword proto-name]}]
                          (str clj-keyword " :" proto-name))
                        sorted))
         "})\n")))
(m/=> keyword-member-map-def [:=> [:cat schema/enum-construct] [:string {:min 1}]])

(defn- malli-enum-def
  "One `(def <root>-proto-enum [:enum …])` source block (proto member names,
   IR order — what `proto-schema` derives its enum schemas from)."
  [{:keys [proto-type] :as construct}]
  (str "(def "
       (csk/->kebab-case-string proto-type)
       "-proto-enum\n"
       "  \""
       proto-type
       " Malli enum (proto member names).\"\n"
       "  ["
       (str/join "\n   " (map str (enum->malli-enum construct)))
       "])\n"))
(m/=> malli-enum-def [:=> [:cat schema/enum-construct] [:string {:min 1}]])

(defn enums->bindings-ns
  "Emit the COMMITTED generated bindings namespace
   (`lvgl-codegen.generated.enums`): per proto-emitted enum, the keyword→int
   authoring map, the keyword→proto-member map and the Malli `[:enum …]`
   schema `proto-schema` derives its enum defs from; per AUTHORING-ONLY enum
   (`lift/authoring-only-typedefs`), the keyword→LVGL-value map alone."
  [enums authoring-enums]
  (str ";; GENERATED by lvgl-codegen.construct.factory — DO NOT EDIT.\n"
       ";; LVGL headers + the numbering registry are the source of truth.\n"
       ";;\n"
       ";; NO REGENERATION PATH EXISTS IN THIS TREE, and no staleness test\n"
       ";; pins this file against a live extraction -- an earlier header here\n"
       ";; claimed both. factory/generate-bindings! takes extracted-enum EDN\n"
       ";; and nothing here produces it, so this committed projection cannot\n"
       ";; currently be re-derived or checked. Four namespaces require it, so\n"
       ";; a drift would be silent. Restoring the extractor retires this note,\n"
       ";; and must land WITH a byte-compare freshness lane.\n"
       "(ns lvgl-codegen.generated.enums\n"
       "  \"Generated LVGL-mirror enum bindings: authoring keyword → proto"
       " wire int\n   maps and Malli enum schemas, per proto-emitted enum;"
       " authoring keyword →\n   LVGL header value maps for the"
       " authoring-only bitmask enums.\")\n\n"
       "(set! *warn-on-reflection* true)\n\n" (str/join "\n" (map keyword-map-def enums))
       "\n" (str/join "\n" (map authoring-keyword-map-def authoring-enums))
       "\n" (str/join "\n" (map keyword-member-map-def enums))
       "\n" (str/join "\n" (map malli-enum-def enums))))
(m/=> enums->bindings-ns
      [:=> [:cat [:vector schema/enum-construct] [:vector schema/enum-construct]]
       [:string {:min 1}]])