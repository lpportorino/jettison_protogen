    /// Radio group (independent of the proxy): clicking option i drives
    /// the subject to i — exactly one checkbox carries CHECKED in the
    /// dumped tree, and the proxy's SYNC echoes mode == i.
    #[test]
    fn radio_group_checks_exactly_one_option() {
        let mut host = new_host();
        let _ = boot(&mut host);
        fn checkbox_states(host: &mut ControlsHost) -> Vec<(i32, i32, bool)> {
            fn collect(node: &serde_json::Value, out: &mut Vec<(i32, i32, bool)>) {
                if node["type"] == "lv_checkbox" {
                    let coords = node["coords"].as_array().expect("coords");
                    let value = |i: usize| coords[i].as_i64().expect("coord") as i32;
                    out.push((
                        (value(0) + value(2)) / 2,
                        (value(1) + value(3)) / 2,
                        node["checked"].as_bool().unwrap_or(false),
                    ));
                }
                if let Some(children) = node["children"].as_array() {
                    for child in children {
                        collect(child, out);
                    }
                }
            }
            let mut out = Vec::new();
            collect(&tree(host), &mut out);
            out.sort_by_key(|(_, y, _)| *y);
            out
        }
        let initial = checkbox_states(&mut host);
        assert_eq!(initial.len(), 4, "four radio options: {initial:?}");
        // checked_when mirrors the subject's initial (1 = Draggable).
        let checked: Vec<bool> = initial.iter().map(|(_, _, c)| *c).collect();
        assert_eq!(
            checked,
            [false, true, false, false],
            "subject initial checks exactly the matching option"
        );
        // Click "Resizable" (index 2, top-to-bottom).
        let (x, y) = (initial[2].0, initial[2].1);
        click(&mut host, x, y);
        let after = checkbox_states(&mut host);
        let checked: Vec<bool> = after.iter().map(|(_, _, c)| *c).collect();
        assert_eq!(
            checked,
            [false, false, true, false],
            "exactly one checkbox CHECKED after the click"
        );
        let reports = host.take_proxy_reports();
        assert!(
            reports
                .iter()
                .any(|r| r.phase == SYNC && r.mode == MODE_RESIZABLE),
            "the proxy's SYNC echoes the subject value: {reports:?}"
        );
        // Clicking the ACTIVE option must not un-check it (the widget's
        // self-toggle is cleared; checked state is purely subject-driven).
        click(&mut host, x, y);
        let again = checkbox_states(&mut host);
        let checked: Vec<bool> = again.iter().map(|(_, _, c)| *c).collect();
        assert_eq!(
            checked,
            [false, false, true, false],
            "re-clicking the active option keeps it checked"
        );
    }
