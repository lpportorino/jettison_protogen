"""Persistent negative controls for the publication freshness gate."""

import os
from pathlib import Path
import shutil
import subprocess
import tempfile
import unittest
from unittest.mock import patch

from corpus_compare import CORPORA, CannotRun, compare, main


class CorpusGateTest(unittest.TestCase):
    """Exercise real Git staging, independent generation, and operational failures."""

    def setUp(self):
        self.temp = tempfile.TemporaryDirectory()
        self.addCleanup(self.temp.cleanup)
        self.root = Path(self.temp.name) / "repo"
        self.generated = Path(self.temp.name) / "generated"
        self.root.mkdir()
        environment = dict(os.environ)
        for key in ("GIT_DIR", "GIT_WORK_TREE", "GIT_INDEX_FILE"):
            environment.pop(key, None)
        self.environment = patch.dict(os.environ, environment, clear=True)
        self.environment.start()
        self.addCleanup(self.environment.stop)
        for directory in CORPORA:
            target = self.root / directory
            target.mkdir(parents=True)
            (target / "manifest.json").write_text("{}\n")
            (target / "example.fig.json").write_text('{"fixture":true}\n')
        shutil.copytree(self.root, self.generated)
        self.run_git("init", "--quiet")
        self.run_git("add", "tools/press/fixtures")

    def run_git(self, *args):
        """Keep tests independent of the surrounding submodule's Git environment."""
        subprocess.run(["git", "-C", str(self.root), *args], check=True, capture_output=True)

    def fixture(self):
        return self.root / CORPORA[0] / "example.fig.json"

    def test_fresh(self):
        self.assertEqual(compare(self.root, self.generated), [])

    def test_unstaged_change_fails_without_rewriting(self):
        self.fixture().write_text("stale")
        self.assertIn("worktree: stale", "\n".join(compare(self.root, self.generated)))
        self.assertEqual(self.fixture().read_text(), "stale")

    def test_staged_only_change_fails(self):
        original = self.fixture().read_bytes()
        self.fixture().write_text("staged stale")
        self.run_git("add", str(self.fixture()))
        self.fixture().write_bytes(original)
        problems = compare(self.root, self.generated)
        self.assertTrue(any(p.startswith("index: stale") for p in problems))
        self.assertFalse(any(p.startswith("worktree:") for p in problems))

    def test_missing_file_fails(self):
        self.fixture().unlink()
        self.assertTrue(any("worktree: missing" in p for p in compare(self.root, self.generated)))

    def test_extra_untracked_file_fails_even_if_ignored(self):
        (self.root / ".gitignore").write_text("extra.json\n")
        (self.fixture().parent / "extra.json").write_text("{}")
        self.assertTrue(any("unexpected" in p for p in compare(self.root, self.generated)))

    def test_staged_extra_file_fails(self):
        (self.fixture().parent / "extra.json").write_text("{}")
        self.run_git("add", "tools/press/fixtures")
        self.assertTrue(any("index: unexpected" in p for p in compare(self.root, self.generated)))

    def test_generator_changed_bytes_fails(self):
        (self.generated / CORPORA[0] / "example.fig.json").write_text("new generated bytes")
        self.assertEqual(len(compare(self.root, self.generated)), 2)

    def test_empty_generation_cannot_run(self):
        (self.generated / CORPORA[0] / "example.fig.json").unlink()
        with self.assertRaisesRegex(CannotRun, "vacuous"):
            compare(self.root, self.generated)

    def test_git_failure_cannot_run(self):
        shutil.rmtree(self.root / ".git")
        with self.assertRaises(CannotRun):
            compare(self.root, self.generated)

    def test_empty_index_cannot_run(self):
        self.run_git("rm", "--cached", "-r", "tools/press/fixtures")
        with self.assertRaisesRegex(CannotRun, "no indexed"):
            compare(self.root, self.generated)

    def test_symlink_cannot_run(self):
        self.fixture().unlink()
        self.fixture().symlink_to(self.generated / CORPORA[0] / "example.fig.json")
        with self.assertRaisesRegex(CannotRun, "nonregular"):
            compare(self.root, self.generated)

    def test_main_distinguishes_failure_from_cannot_run(self):
        with patch("sys.argv", ["gate", str(self.root), str(self.generated)]):
            self.assertEqual(main(), 0)
            self.fixture().write_text("stale")
            self.assertEqual(main(), 1)
            shutil.rmtree(self.root / ".git")
            self.assertEqual(main(), 2)

    def run_gate(self, fail_generator=False):
        """Drive the actual shell boundary with a controlled generator process."""
        source = Path(__file__).resolve().parents[1]
        tool = self.root / "tools/press"
        (tool / "test").mkdir()
        shutil.copy2(source / "check_corpus.sh", tool / "check_corpus.sh")
        shutil.copy2(source / "test/corpus_compare.py", tool / "test/corpus_compare.py")
        binaries = Path(self.temp.name) / "bin"
        binaries.mkdir()
        executable = binaries / "clojure"
        executable.write_text(
            "#!/usr/bin/env python3\n"
            "import os, pathlib, shutil, sys\n"
            "assert 'PRESS_ROOT' not in os.environ\n"
            "assert sys.argv[1] == '-J-Dpress.root=' + os.environ['CANARY_ROOT']\n"
            "assert sys.argv[2] == '-M:corpus' and len(sys.argv) == 4\n"
            "if os.environ.get('CANARY_GENERATOR_FAILURE'): sys.exit(1)\n"
            "stage = pathlib.Path(sys.argv[3])\n"
            "assert stage.resolve() != pathlib.Path(os.environ['CANARY_ROOT']).resolve()\n"
            "shutil.copytree(pathlib.Path(os.environ['CANARY_EXPECTED']) / 'tools', stage / 'tools')\n"
        )
        executable.chmod(0o755)
        environment = dict(os.environ)
        environment.update(
            PATH=str(binaries) + os.pathsep + environment["PATH"],
            PRESS_ROOT="/wrong/consumer/root",
            CANARY_ROOT=str(self.root),
            CANARY_EXPECTED=str(self.generated),
        )
        if fail_generator:
            environment["CANARY_GENERATOR_FAILURE"] = "1"
        return subprocess.run(
            ["bash", str(tool / "check_corpus.sh")],
            cwd="/",
            env=environment,
            capture_output=True,
            text=True,
            check=False,
        )

    def test_gate_pins_root_and_generates_elsewhere(self):
        result = self.run_gate()
        self.assertEqual(result.returncode, 0, result.stderr)

    def test_gate_stale_worktree_fails_without_repair(self):
        self.fixture().write_text("stale")
        result = self.run_gate()
        self.assertEqual(result.returncode, 1, result.stderr)
        self.assertIn("worktree: stale", result.stderr)
        self.assertEqual(self.fixture().read_text(), "stale")

    def test_generator_failure_is_cannot_run(self):
        result = self.run_gate(fail_generator=True)
        self.assertEqual(result.returncode, 2, result.stderr)
        self.assertIn("CANNOT RUN: corpus generator failed", result.stderr)
