(def ^:private derive-proposal (pl/propose pl/protogen-spec))
(def ^:private audit-proposal (pl/propose (pl/with-pinned pl/protogen-spec #{:accent-bg})))
(def ^:private ladder-proposal
  (pl/propose (pl/without-roles pl/protogen-spec
                                #{:status-error :status-success :status-warning})))

;; ── the dead-band fixture ───────────────────────────────────────────────────
;; A fill NO ink can clear the 6:1 text shall against: black reaches 3.69:1 and
;; white only 5.70:1, so its BEST case falls short and the solve must be refused
;; before any search. That is the state `:reference-infeasible` exists to name.
;;
;; It is OWNED HERE, as a test constant, and that is the point. This value is
;; what `:accent-bg` shipped before it forked per mode, and the canaries below
;; used to reach it by pinning the live role. Then the fork REPAIRED the dead
;; band — dark #B18AF4 best-cases at 7.81:1, light #5C14D7 at 8.28:1 — and four
;; canaries went red for having their subject fixed underneath them. A canary
;; coupled to a value it does not test fails on the day that value improves,
;; which is precisely backwards. Section 6 below already builds synthetic specs
;; "for the statuses the shipped palette does not happen to hit"; a dead band is
;; now one of those.
(def ^:private dead-band-fill "#7C3AED")

(defn- with-dead-band-accent
  "`spec` with :accent-bg forced to the dead-band fill. Mode-invariant, so both
   modes are equally infeasible and a per-mode difference cannot be mistaken for
   the effect under test."
  [spec]
  (update spec
          :roles
          (fn [roles]
            (mapv (fn [r]
                    (if (= :accent-bg (:role r))
                      (assoc r :shipped dead-band-fill :mode-invariant? true)
                      r))
                  roles))))

;; PINNED: accent-bg is frozen in the dead band, so accent-text — whose only
;; constraint is `text-pair :accent-bg` — cannot be solved at all.
(def ^:private dead-band-pinned-proposal
  (pl/propose (pl/with-pinned (with-dead-band-accent pl/protogen-spec)
                #{:accent-bg})))

;; FREE: the same dead band, but the solver may move accent-bg off it. This is
;; the DISCRIMINATOR for the test above — same role, same hue, same chroma
;; budget, different verdict — so the infeasibility is attributable to the
;; pinned VALUE and to nothing about accent-text.
(def ^:private dead-band-free-proposal
  (pl/propose (with-dead-band-accent pl/protogen-spec)))

(defn- resolved-map
  "Rebuild {mode {role realized}} from a proposal's EMITTED HEXES ONLY. This is
   the independent path: it never reads the solver's own `:evaluations`, so an
   agreement here is evidence rather than a restatement."
  [proposal]
  (reduce (fn [acc [[role-key mode] cell]]
            (assoc-in acc [mode role-key] (pl/realize-hex (:hex cell))))
          {}
          (:palette proposal)))

(defn- role-by-key [spec k]
  (first (filter #(= k (:role %)) (:roles spec))))

(deftest test-every-proposed-colour-re-verifies-from-its-own-hex
  (testing "re-measuring each solved cell FROM THE EMITTED HEX still clears every floor"
    (doseq [[label proposal spec]
            [[:derive derive-proposal pl/protogen-spec]
             [:audit audit-proposal (pl/with-pinned pl/protogen-spec #{:accent-bg})]
             [:ladder ladder-proposal
              (pl/without-roles pl/protogen-spec
                                #{:status-error :status-success :status-warning})]]]
      (let [resolved (resolved-map proposal)]
        (doseq [[[role-key mode] cell] (:palette proposal)
                :when (not= :pinned (:status cell))
                :let [role (role-by-key spec role-key)
                      subject (pl/realize-hex (:hex cell))
                      ;; A mode-invariant role must hold in every mode it was
                      ;; solved across, so re-verify it in each.
                      check-modes (if (:mode-invariant? role) (:modes spec) [mode])]
                c (:constraints role)
                m check-modes
                :when (or (nil? (:modes c)) (contains? (:modes c) m))]
          (let [ev (pl/evaluate-constraint c subject (get resolved m) m)]
            (is (:satisfied? ev)
                (str (name label) " " (name role-key) "/" (name m) " " (:hex cell)
                     " fails " (pl/constraint-label c)
                     " on re-measurement: " (format "%.4f" (double (:wcag-ratio ev)))
                     " vs bound " (double (:bound-wcag-ratio ev))
                     " (" (name (:bound-kind ev)) ")"))))))))

(deftest test-a-refused-cell-never-appears-in-the-palette
  (testing "an unjudged or impossible cell is a finding, not a best-effort colour"
    (doseq [[label proposal] [[:derive derive-proposal]
                              [:audit audit-proposal]
                              [:ladder ladder-proposal]]]
      (doseq [f (:findings proposal)
              m (:modes f)]
        (is (not (contains? (:palette proposal) [(:role f) m]))
            (str (name label) " " (name (:role f)) "/" (name m)
                 " is reported as " (name (:status f))
                 " and ALSO carries a proposed colour")))
      (is (pos? (count (:findings proposal)))
          (str (name label) " reports no findings at all — if that is genuine"
               " the taxonomy is untested by this spec")))))

(deftest test-proposal-is-deterministic
