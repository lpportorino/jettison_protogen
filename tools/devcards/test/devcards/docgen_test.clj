    (with-tree ["a/README.md" "a/stale.jpg"]
      (fn [root written]
        (let [stale (pick written "a/stale.jpg")]
          (is (thrown-with-msg? clojure.lang.ExceptionInfo #"claimed ZERO paths"
                                (docgen/prune-orphans!
                                 {:root root
                                  :claimed []
                                  :required-claims [(pick written "a/README.md")]
