(ns lvgl-codegen.palette-ladder-test
  "Executable proof of the palette derivation's three separable claims: that its
   contrast arithmetic agrees with the implementation this repo already ships,
   that its search space and its report cannot disagree about a value, and that
   its four refusal statuses are told apart by the clause each one names rather
   than by whichever branch happened to fire first.

   HOW TO READ A CANARY HERE. Every deftest whose job is to prove a gate fires
   carries a `REVERT-TO-BREAK:` line naming the ONE production expression to
   mutate, and a CONTROL naming a test that must stay GREEN under that mutation.
   Without the control a red proves only that something broke; with it, the red
   is attributable to the clause. Mutation evidence for every one of them is in
   FINAL_REPORT.md.

   WHAT THIS SUITE DOES NOT TOUCH. It renders nothing, reads no manifest and
   moves no golden. `lvgl-codegen.palette-ladder` emits a PROPOSAL and this
   suite reads it; neither writes `edn/tokens.edn` or the generated header."
  (:require [clojure.set :as set]
            [clojure.test :refer [deftest is testing]]
            [lvgl-codegen.instrument :as inst]
            [lvgl-codegen.palette-ladder :as pl]))

(set! *warn-on-reflection* true)

