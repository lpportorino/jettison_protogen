// Animation clock: the press transition is a PURE FUNCTION of the
// accumulated controls_tick(ms) time. controls_tick = lv_tick_inc(dt)
// + lv_timer_handler — no wall clock enters the module — and the
// default theme attaches an 80 ms press transition (bg/recolor/grow)
// to THEMED buttons (LV_THEME_DEFAULT_TRANSITION_TIME, vendored LVGL
// default 80; bare widgets strip theme styles and with them the
// transition). MEASURED shape (2026-07-19 camp probe): after the
// press latches on an indev tick, single-jump schedules render
// genuinely MID-transition frames for jumps of ~36–70 ms (center
// pixel walks 243→228→222→218→214→209) and saturate by ~80 ms; all
// timers (indev, anim, refresh) are 33 ms-periodic in TICK time.
// TRAP the probe hit twice: the refresh timer needs a FULL 33 ms of
// tick time after the anim step lands its invalidation — a 1 ms
// "flush" tick renders NOTHING regardless of jump size, so a
// clock-advance must be followed by a 33 ms render pass before
// reading pixels (a single-tick 5 ms-vs-200 ms probe reads the
// pre-anim frame both times and wrongly concludes "no animation").
// These pins
// arm a host-side dt-sensitivity gate: measured-dt hosts must see
// different pixels DURING the transition window, and identical dt
// schedules must stay byte-identical (determinism doctrine).
// ═══════════════════════════════════════════════════════════════════

mod anim_clock {
    use super::*;
    use lvgl_harness::proto::ui::style_property::Value;
    /// A THEMED button screen (prost-built): explicit W×H root + a 100×40
    /// button at (60,50). No `bare` anywhere — the default theme's press
    /// transition styles must survive.
    fn themed_button_screen() -> Vec<u8> {
        let size = |w: u32, h: u32| ui::StyleGroup {
            variants: vec![ui::StyleVariant {
                properties: vec![
                    ui::StyleProperty {
                        r#type: ui::StylePropertyType::PropWidth as i32,
                        value: Some(Value::UintValue(w)),
                    },
                    ui::StyleProperty {
                        r#type: ui::StylePropertyType::PropHeight as i32,
                        value: Some(Value::UintValue(h)),
                    },
                ],
                ..Default::default()
            }],
            ..Default::default()
        };
        let button = ui::WidgetNode {
            r#type: ui::WidgetType::WidgetButton as i32,
            uid: 42,
            x: 60,
            y: 50,
            style_groups: vec![size(100, 40)],
            children: vec![ui::WidgetNode {
                r#type: ui::WidgetType::WidgetLabel as i32,
                uid: 43,
                text: "Go".into(),
                ..Default::default()
            }],
            ..Default::default()
        };
        let root = ui::WidgetNode {
            r#type: ui::WidgetType::WidgetObj as i32,
            uid: 100,
            children: vec![button],
            style_groups: vec![size(WIDTH, HEIGHT)],
            ..Default::default()
        };
        ui::Screen {
            root: Some(root),
            ..Default::default()
        }
        .encode_to_vec()
    }
    /// Load the themed button, settle, PRESS its center (no release), latch
    /// the pressed state on an indev-read tick, advance the clock by
    /// `dt_after_latch` in one tick, then run ONE 33 ms render pass and read
    /// the framebuffer. The flush pass must be a FULL refresh period (the
    /// module-doc trap): the refresh timer is 33 ms-periodic in tick time,
    /// so after a big clock jump the anim step lands its invalidation but
    /// the NEXT refresh is 33 tick-ms away — a shorter flush reads the
    /// pre-anim frame regardless of how far the clock jumped.
    fn press_then_tick(dt_after_latch: u32) -> Vec<u8> {
        let mut host = new_host();
        host.set_breakpoint(DEFAULT_BP).expect("set_breakpoint");
        host.set_theme_dark(DEFAULT_THEME).expect("set_theme_dark");
        host.set_dpi(DPI).expect("set_dpi");
        host.load_ui(&themed_button_screen()).expect("load_ui");
        for _ in 0..10 {
            let _ = host.tick(16).expect("tick");
        }
        let (x, y) = widget_center(&mut host, "lv_button");
        press_px(&mut host, x, y);
        // One 33 ms tick: the indev read timer latches PRESSED and the theme
        // transition STARTS (anim t=0) — identical prefix for every schedule.
        let _ = host.tick(33).expect("tick");
        let _ = host.tick(dt_after_latch).expect("tick");
        let _ = host.tick(33).expect("tick"); // full refresh period — flush
        host.read_framebuffer().expect("framebuffer")
    }
    /// Same pointer events, DIFFERENT dt schedules → different pixels.
    /// MEASURED window (2026-07-19 camp probe, center-pixel walk
    /// 243→228→222→218→214→209): mid-transition frames render for jumps of
    /// ~36–70 ms after the latch (+ the 33 ms flush); the recolor saturates
    /// by ~80 ms. So 50 ms is a genuinely MID frame and 300 ms is the final
    /// one. A time-blind renderer (or a schedule that never samples inside
    /// the window) would make these identical — this is the dt-sensitivity
    /// pin the host gate arms on.
    #[test]
    fn press_transition_pixels_depend_on_dt() {
        let mid = press_then_tick(50);
        let done = press_then_tick(300);
        assert_differ(
            "50 ms vs 300 ms after the press latch must differ mid-transition",
            &mid,
            &done,
            0.0001,
        );
    }
    /// Same pointer events, SAME dt schedule → byte-identical pixels
    /// (the animation clock is accumulated tick ms, never wall time).
    #[test]
    fn press_transition_is_deterministic_in_tick_time() {
        let a = press_then_tick(50);
        let b = press_then_tick(50);
        assert_identical("identical dt schedules must render identically", &a, &b);
    }
}
