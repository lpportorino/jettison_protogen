(def ^:private unreachable-spec
  "One solved role, ONE constraint, a reference that is comfortably hostable,
   and a chroma the role refuses to give up. So it cannot be
   :reference-infeasible (the reference hosts), cannot be :reference-conflict
   (there is one constraint), and cannot be :blocked-upstream (the reference is
   pinned) — the only status left is the one under test."
  {:spec-id :synthetic-unreachable
   :modes [:dark]
   :roles [{:role :ink-surface :kind :pinned :shipped {:dark "#000000"}}
           {:role :saturated-ink
            :kind :solved
            :shipped {:dark "#0000FF"}
            :chroma-retain-min 0.9
            :constraints [{:kind :contrast-min :against :ink-surface
                           :floor :text-should :provenance :inferred}]}]})

(deftest test-unreachable-in-gamut-is-a-different-status
  ;; REVERT-TO-BREAK: in `solve-cell`, disable the chroma-retention filter —
  ;;   `(filterv #(>= (double (:oklch-c-used %)) (- chroma-min 1.0e-12)))`
  ;;   -> `(filterv #(>= (double (:oklch-c-used %)) -1.0))`
  ;; CONTROL: test-reference-infeasible-fires-and-names-the-upstream-role stays
  ;; GREEN. Under the mutation the role desaturates to a pale grey and solves,
  ;; so the gamut refusal is attributable to the chroma budget and not to the
  ;; floor or the reference.
  (testing "a hostable reference plus an unaffordable chroma is a GAMUT refusal"
    (let [proposal (pl/propose unreachable-spec)
          f (finding-for proposal :saturated-ink :dark)]
      (is (some? f) "the role solved; the synthetic spec no longer demonstrates anything")
      (is (= :unreachable-in-gamut (:status f))
          (str "expected a gamut refusal, got " (pr-str (:status f))))
      (is (= :floor-unmet-at-chroma-budget (:reason f))
          (str "the refusal is the right status for the wrong reason: "
               (pr-str (:reason f))))
      (is (= 0.9 (:chroma-retain-min f)))
      (is (seq (:unmet f)) "the finding does not name the constraint it could not meet")))
  (testing "and the reference genuinely could host something, so it is not the reference's fault"
    (is (>= (pl/max-hostable-ratio (pl/wcag-y (pl/hex->rgb8 "#000000")))
            (pl/floor-ratio :text-should))))
  (testing "the OTHER gamut reason is reported distinctly, not folded into the first"
    ;; Demanding 100% of a chroma that already sits ON the gamut boundary leaves
    ;; a measure-zero lightness set, so nothing is emittable at all - a
    ;; different repair (relax the chroma budget) from the case above (move the
    ;; hue or the floor), and a status that did not separate them would say the
    ;; same thing about both.
    (let [f (finding-for
             (pl/propose (assoc-in unreachable-spec [:roles 1 :chroma-retain-min] 1.0))
             :saturated-ink :dark)]
      (is (= :unreachable-in-gamut (:status f)))
      (is (= :no-candidate-at-chroma-budget (:reason f)))
      (is (nil? (:unmet f))
          "a cell with no candidates at all cannot name an unmet constraint"))))

