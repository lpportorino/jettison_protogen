// Display resize: controls_resize(w, h) reallocates the framebuffer +
// draw buffers and relayouts. pct-100 roots must track the new size,
// repeated cycles must stay stable (the resize path once OOM'd from
// peak double-allocation), and invalid dimensions must fail loudly.
// ═══════════════════════════════════════════════════════════════════

mod display_resize {
    use super::*;
    /// Root coords from the dumped tree — the live display size oracle.
    fn root_coords(host: &mut ControlsHost) -> (i64, i64) {
        let dump = host.dump_tree().expect("dump_tree");
        let tree: serde_json::Value = serde_json::from_str(&dump).expect("tree json");
        let coords = tree["coords"].as_array().expect("coords");
        (
            coords[2].as_i64().expect("x2") + 1,
            coords[3].as_i64().expect("y2") + 1,
        )
    }
    fn tick_settle(host: &mut ControlsHost) {
        for _ in 0..RENDER_TICKS {
            let _ = host.tick(TICK_MS).expect("tick");
        }
    }
    /// Resize to `w`×`h`, settle, and assert the framebuffer size, the
    /// pct-100 root extent, and non-empty content all track.
    fn resize_and_verify(host: &mut ControlsHost, w: u32, h: u32) {
        host.resize(w, h).expect("resize");
        tick_settle(host);
        let fb = host.read_framebuffer().expect("framebuffer");
        assert_eq!(fb.len(), (w * h * 4) as usize, "{w}x{h}: framebuffer size");
        assert_not_empty(&format!("{w}x{h}: content"), &fb);
        let (root_w, root_h) = root_coords(host);
        assert_eq!(
            (root_w, root_h),
            (i64::from(w), i64::from(h)),
            "{w}x{h}: pct-100 root tracks the new display size"
        );
    }
    #[test]
    fn resize_down_relayouts_and_renders() {
        let mut host = new_host();
        let _ = render(&mut host, "vr_bp_color");
        resize_and_verify(&mut host, 200, 150);
    }
    #[test]
    fn resize_up_relayouts_and_renders() {
        let mut host = new_host();
        let _ = render(&mut host, "vr_bp_color");
        resize_and_verify(&mut host, 640, 480);
    }
    /// The OOM-regression guard: repeated grow/shrink cycles keep
    /// rendering (the resize path frees old buffers before allocating
    /// new ones to halve peak memory).
    #[test]
    fn repeated_resize_cycles_stay_stable() {
        let mut host = new_host();
        let _ = render(&mut host, "vr_bp_color");
        for _ in 0..3 {
            resize_and_verify(&mut host, 640, 480);
            resize_and_verify(&mut host, 200, 150);
            resize_and_verify(&mut host, WIDTH, HEIGHT);
        }
    }
    #[test]
    fn resize_rejects_zero_dimensions() {
        let mut host = new_host();
        let _ = render(&mut host, "vr_bp_color");
        assert!(host.resize(0, 100).is_err(), "zero width must be rejected");
        assert!(host.resize(100, 0).is_err(), "zero height must be rejected");
        // The display must still be usable after the rejected calls.
        resize_and_verify(&mut host, WIDTH, HEIGHT);
    }
    /// Resizing must not break the responsive machinery: after a resize,
    /// a live breakpoint switch still restyles.
    #[test]
    fn resize_then_breakpoint_switch_restyles() {
        let mut host = new_host();
        let fb_before = render_fixture(&mut host, "vr_bp_color", 0, DEFAULT_THEME);
        assert!(analysis::has_color(&fb_before, RED, COLOR_TOLERANCE));
        host.resize(640, 480).expect("resize");
        tick_settle(&mut host);
        host.set_breakpoint(3).expect("set_breakpoint");
        tick_settle(&mut host);
        let fb = host.read_framebuffer().expect("framebuffer");
        assert!(
            analysis::has_color(&fb, ACCENT_DARK, COLOR_TOLERANCE),
            "xl tier color renders after resize + bp switch"
        );
    }
}
