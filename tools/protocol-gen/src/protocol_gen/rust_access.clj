(ns protocol-gen.rust-access
  "The per-group ACCESS MODULE, in Rust, derived from the same projection the
   `.proto` text and the permission mirror are derived from.

   WHY RUST AND NOT EDN. The permission mirror already carries direction, and
   it is EDN: a consumer reads it with a parser, at run time, and a typo in the
   key it looks under is a nil rather than a compile error. This module carries
   the same fact as a CLOSED, TYPED surface, so `may this group send message
   X?` is answered by the compiler.

   WHY NOT A RUST MESSAGE EMITTER, which is the thing this file must not become.
   The per-group `.proto` already reaches Rust through a consumer's prost
   pipeline, and a message the policy withheld is simply not in that group's
   generated module — so a forbidden message is ALREADY a compile error there.
   A second emitter for the same shapes would give one wire contract two
   sources, which is the disagreement the whole tool is arranged to make
   unrepresentable. What `.proto` structurally cannot carry is DIRECTION: proto
   describes a shape, and `may send` versus `may receive` is not a shape. That
   gap, and nothing else, is what this namespace fills.

   MESSAGE LEVEL AND NO LOWER. proto3 field presence is absent from the
   descriptor database by construction, so a per-field access surface would be
   claiming a distinction its input cannot supply.

   WHY IT IS EMITTED FROM THE SAME RUN AND THE SAME VALUE — the argument
   `protocol-gen.mirror`'s docstring makes, and it is the reason this is a
   sibling of that namespace rather than a second pass: two derivations of one
   grant disagree the first time one of them is wrong, and deriving both from
   one projection leaves nothing for them to disagree ABOUT.

   WHAT IT IS NOT. Like the mirror, it is a record of what the generator was
   told, not an enforcement mechanism. Nothing here stops a consumer sending a
   message it may not send; what stops that is the group's schema not being
   able to express one, and this module is what lets a reviewer — and a
   consumer's own `if` — see the direction the schema has nowhere to put.

   THE ONE INPUT CLASS THIS EMISSION CANNOT EXPRESS, stated rather than
   approximated. A variant is the message's emitted `.proto` name VERBATIM, so
   a message whose emitted name is a word Rust reserves produces a module that
   does not compile.

   REACHING IT NEEDS A PROTO FILE WITH NO PACKAGE, because an emitted name is a
   source id with its dots turned into underscores and a packaged message
   therefore carries its package as a prefix. AND THE CASE NOT TO REASON AWAY
   IS `Self`: reading Rust's reserved words as lowercase ASCII makes this look
   unreachable, and that reading is wrong — `Self` is reserved, it cannot even
   be spelled as a raw identifier, and it is a perfectly ordinary proto message
   name.

   It is caught loudly, by rustc: the canary compiles every emitted module, and
   a consumer's own build compiles theirs. It is deliberately NOT caught by a
   hand-kept list of Rust's reserved words here, because such a list is a copy
   of an external fact that rots silently in the direction of a MISSING word,
   and a silent rot is worse than a compile error that names the identifier."
  (:require [clojure.string :as str]
            [malli.core :as m]
            [protocol-gen.projection :as projection]
            [protocol-gen.rust-lit :as rust-lit]))

(set! *warn-on-reflection* true)

(def banner
  "The header every emitted module carries.

   It says what wrote the file, what the file is FOR, and — the beat the
   `.proto` banner has no need of — what the file deliberately does not carry,
   because `a generated Rust module beside a generated .proto` reads as message
   bindings until it says otherwise."
  (str "// GENERATED by protocol-gen — DO NOT EDIT.\n"
       "// Source of truth: the access policy named in this run's arguments,\n"
       "// projected in the same run and from the same value as this group's\n"
       "// `.proto` and the permission mirror beside it.\n"
       "//\n"
       "// IT CARRIES ACCESS FACTS ONLY — which messages this group holds a grant\n"
       "// for, and in which direction. It declares no message shapes: those reach\n"
       "// Rust through this group's `.proto`, and a second source for them would\n"
       "// be a second opinion about one wire contract.\n"
       "//\n"
       "// Include it into a module of its own — the item names are short and are\n"
       "// NOT unique across groups. Hand edits are destroyed by the next run.\n"))

(def access-variants
  "Every access set a grant can carry, mapped to the Rust variant that names
   it.

   TOTAL OVER THE POLICY, and that is checkable rather than hopeful:
   `protocol-gen.policy/grant` closes `:access` to a non-empty subset of
   `#{:read :write}`, so these three are every value that can arrive. A set
   outside this map is a fault in the projection rather than a case to render,
   and `access-variant` throws on one."
  {#{:read} "Read"
   #{:write} "Write"
   #{:read :write} "ReadWrite"})

(defn access-variant
  "The Rust `Access` variant naming `access`, or a throw naming the set.

   THROWS RATHER THAN DEFAULTING. A default here would render some direction
   for a set nobody anticipated, and a direction rendered from a guess is the
   one failure this module exists to make impossible."
  [access]
  (or (get access-variants access)
      (throw (ex-info "Not an access set this emitter can name"
                      {:access access :known (vec (sort-by str (keys access-variants)))}))))

(m/=> access-variant
      [:=> [:cat [:set [:enum :read :write]]] [:string {:min 1}]])

(defn granted-messages
  "`group`'s projected messages in SOURCE-ID order.

   Sorted here and nowhere else, so every list this namespace emits — the
   variants, each match's arms, and the `MESSAGES` table — is in one order and
   two runs over the same projection write identical bytes. The projection's
   own order is the policy's grant order, which is an authoring convenience and
   not a fact about the group."
  [group]
  (vec (sort-by :id (:messages group))))

(m/=> granted-messages
      [:=> [:cat projection/projected-group] [:vector projection/projected-message]])

(defn- doc-lines
  "A `///` doc comment, one emitted line per string in `texts`, each indented
   by `indent` spaces.

   WRAPPED BY THE CALLER RATHER THAN HERE. A width this function chose would be
   a layout rule with no owner; a caller that knows what it is saying can break
   its own prose where the sentence does."
  [indent texts]
  (str/join "\n" (for [text texts]
                   (str (apply str (repeat indent \space)) "/// " text))))

(defn- match-arms
  "The body of a `match self { … }`, one arm per message, indented to sit
   inside an `impl` method. `arm-value` renders the value a message maps to."
  [messages arm-value]
  (str/join "\n"
            (for [msg messages]
              (str "            Self::" (:proto-name msg) " => " (arm-value msg) ","))))

(defn- const-fn
  "One `pub const fn` on `Message` whose whole body is a match over `self`.

   THE EMPTY-ENUM CASE IS THE REASON THIS IS ONE FUNCTION RATHER THAN THREE
   COPIES. A group whose projection granted no message emits an uninhabited
   `Message`, and `match self {}` with no arms is exactly how Rust spells a
   match on one — a shape easy to get wrong three times and right once."
  [{:keys [name-str return doc messages arm-value]}]
  (str (doc-lines 4 doc) "\n"
       "    #[must_use]\n"
       "    pub const fn " name-str "(self) -> " return " {\n"
       (if (seq messages)
         (str "        match self {\n" (match-arms messages arm-value) "\n        }\n")
         "        match self {}\n")
       "    }\n"))

(defn- message-enum
  "The closed `Message` enum: one variant per granted message, and nothing
   else."
  [messages]
  (str "/// Every message this group holds a grant for, and nothing else.\n"
       "///\n"
       "/// CLOSED ON PURPOSE: a message this group was not granted has no variant\n"
       "/// here, so naming one is a compile error rather than a lookup returning\n"
       "/// nothing at run time.\n"
       "///\n"
       "/// Each variant is the message's name in this group's `.proto`, VERBATIM.\n"
       "/// A camel-cased variant would be a SECOND name for a message the\n"
       "/// `.proto` emission has already named, and camel-casing is not\n"
       "/// injective: `pgfix_command` and `pgfix_Command` are two distinct\n"
       "/// `.proto` names that collide on one variant. So the second name could\n"
       "/// disagree with the first about which message a variant means, and the\n"
       "/// collision check the projection already runs would not see it.\n"
       "#[allow(non_camel_case_types)]\n"
       "#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, PartialOrd, Ord)]\n"
       "pub enum Message {\n"
       (str/join "\n" (for [msg messages]
                        (str (doc-lines 4 [(str "`" (:id msg) "`, granted "
                                                (str/join " and " (map name (sort (:access msg))))
                                                ".")])
                             "\n    " (:proto-name msg) ",")))
       (when (seq messages) "\n")
       "}\n"))

(def access-enum
  "The `Access` enum and its two predicates.

   THE PREDICATES ARE THE CONSUMER-FACING SURFACE, not the variant names: a
   consumer asks `may_write()` and never matches on `ReadWrite`, so adding a
   fourth direction later could not silently change the meaning of a call site
   that already reads correctly."
  (str "/// What this group may do with a message: the direction a grant carries.\n"
       "///\n"
       "/// Closed, because the access policy's own set is closed and non-empty —\n"
       "/// these three are every value a grant can hold.\n"
       "#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, PartialOrd, Ord)]\n"
       "pub enum Access {\n"
       "    /// This group may RECEIVE the message.\n"
       "    Read,\n"
       "    /// This group may SEND the message.\n"
       "    Write,\n"
       "    /// This group may both receive and send it.\n"
       "    ReadWrite,\n"
       "}\n"
       "\n"
       "impl Access {\n"
       "    /// Whether this group may RECEIVE a message carrying this grant.\n"
       "    #[must_use]\n"
       "    pub const fn may_read(self) -> bool {\n"
       "        matches!(self, Self::Read | Self::ReadWrite)\n"
       "    }\n"
       "\n"
       "    /// Whether this group may SEND a message carrying this grant.\n"
       "    #[must_use]\n"
       "    pub const fn may_write(self) -> bool {\n"
       "        matches!(self, Self::Write | Self::ReadWrite)\n"
       "    }\n"
       "}\n"))

(defn module
  "The whole emitted Rust module for one projected group.

   Nothing here decides WHAT is emitted — the policy settled that two passes
   earlier — and nothing here reads a field: the access fact this module
   carries is a property of the grant, and a per-field surface would claim a
   distinction the descriptor database does not carry."
  [group]
  (let [messages (granted-messages group)]
    (str banner
         "\n/// The access group this module describes, by its policy id.\n"
         "pub const GROUP: &str = " (rust-lit/string-literal (name (:id group))) ";\n"
         "\n/// The proto package this group's `.proto` declares.\n"
         "pub const PACKAGE: &str = " (rust-lit/string-literal (:package group)) ";\n"
         "\n" access-enum
         "\n" (message-enum messages)
         "\nimpl Message {\n"
         (const-fn {:name-str "source_id"
                    :return "&'static str"
                    :doc ["The message's id in the descriptor database or the mint"
                          "— the name the access policy grants it by."]
                    :messages messages
                    :arm-value (comp rust-lit/string-literal :id)})
         "\n"
         (const-fn {:name-str "proto_name"
                    :return "&'static str"
                    :doc ["The message's name in this group's `.proto`, and so the"
                          "message a prost pipeline generates from it."]
                    :messages messages
                    :arm-value (comp rust-lit/string-literal :proto-name)})
         "\n"
         (const-fn {:name-str "access"
                    :return "Access"
                    :doc ["What this group may do with the message."]
                    :messages messages
                    :arm-value #(str "Access::" (access-variant (:access %)))})
         "}\n"
         "\n/// Every granted message, in source-id order.\n"
         "pub const MESSAGES: [Message; " (count messages) "] = [\n"
         (str/join "" (for [msg messages] (str "    Message::" (:proto-name msg) ",\n")))
         "];\n")))

(m/=> module [:=> [:cat projection/projected-group] [:string {:min 1}]])
