/// FNV-1a-32 over bytes — matches main.c `fnv1a32` and the codegen's
/// `emit_proto/fnv1a-32-bytes`. The `base_hash` a ScreenPatch must carry to
/// pass `controls_apply_patch`'s base-hash gate is this hash of the loaded
/// `.pb`. File-scope because more than one module builds patches against a
/// screen it loaded (`pointer_routing`, `host_event_envelope`) — one home.
fn fnv1a32(data: &[u8]) -> u32 {
    let mut h: u32 = 2166136261;
    for &b in data {
        h ^= u32::from(b);
        h = h.wrapping_mul(16777619);
    }
    h
}
