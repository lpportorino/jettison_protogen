(def ^:private sample-backgrounds
  ["#0A0A12" "#12121F" "#1E1E2E" "#7C3AED" "#0E7490" "#F59E0B" "#10B981"
   "#EF4444" "#C0C0A8" "#D0D0C0" "#F0F0E8" "#808080" "#000000" "#FFFFFF"])

(defn- brute-force-best-ratio
  "The best contrast any of a wide sample of emittable colours reaches against
   `y-ref` — every grey, both extremes, and the saturated token colours."
  ^double [^double y-ref]
  (let [greys (map (fn [v] [v v v]) (range 0 256))
        others (map pl/hex->rgb8 sample-backgrounds)]
    (reduce max 0.0 (map #(pl/wcag-ratio (pl/wcag-y %) y-ref) (concat greys others)))))

(deftest test-max-hostable-ratio-is-a-tight-upper-bound
  (testing "no emittable colour beats the closed form, and one attains it"
    (doseq [hex sample-backgrounds]
      (let [y (pl/wcag-y (pl/hex->rgb8 hex))
            bound (pl/max-hostable-ratio y)
            best (brute-force-best-ratio y)]
        (is (<= best (+ bound 1.0e-9))
            (str hex ": brute force found " best " above the closed form " bound))
        (is (< (Math/abs (- best bound)) 1.0e-9)
            (str hex ": the closed form " bound
                 " is not ATTAINED — best emittable is " best
                 ", so :reference-infeasible would be a conservative guess"
                 " rather than a proof"))))))

(deftest test-hostable-band-brackets-the-dead-zone
  (testing "above the critical ratio the band is a real dead zone"
    ;; The closed form bottoms out at ~4.58:1, so a floor BELOW that has no dead
    ;; zone at all. Asserting one for every floor would be asserting a property
    ;; two thirds of them do not have.
    (doseq [floor-key [:text-shall :text-should]]
      (let [f (pl/floor-ratio floor-key)
            {:keys [wcag-y-max-for-light-foreground wcag-y-min-for-dark-foreground]}
            (pl/hostable-band f)]
        (is (< wcag-y-max-for-light-foreground wcag-y-min-for-dark-foreground)
            (str (name floor-key) ": the band is empty or inverted, so nothing is dead"))
        ;; Just inside each edge the floor is met; strictly between them it is not.
        (is (>= (pl/max-hostable-ratio (- wcag-y-max-for-light-foreground 1.0e-9)) f))
        (is (>= (pl/max-hostable-ratio (+ wcag-y-min-for-dark-foreground 1.0e-9)) f))
        (is (< (pl/max-hostable-ratio
                (* 0.5 (+ wcag-y-max-for-light-foreground wcag-y-min-for-dark-foreground)))
               f)
            (str (name floor-key)
                 ": the midpoint of the band is supposed to be unreachable")))))
  (testing "the 3:1 non-text floor has NO dead zone, and the band says so by inverting"
    (let [f (pl/floor-ratio :non-text)
          {:keys [wcag-y-max-for-light-foreground wcag-y-min-for-dark-foreground]}
          (pl/hostable-band f)]
      (is (> wcag-y-max-for-light-foreground wcag-y-min-for-dark-foreground)
          "the non-text band is not inverted, so it claims a dead zone that does not exist")
      (doseq [y (range 0.0 1.0001 0.02)]
        (is (>= (pl/max-hostable-ratio y) f)
            (str "luminance " y " is reported unhostable at the 3:1 floor"))))))

