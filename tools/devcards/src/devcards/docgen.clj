(ns devcards.docgen
  "Generic Markdown doc-gen primitives shared by the devcards gallery generator
   (devcards.docs — the committed public per-widget pages) and any consumer that
   dogfoods the same documentation axis over its own render set (asgard's
   private screen-corpus docs). Extracted verbatim from devcards.docs so BOTH
   producers share one GFM table builder, one DO-NOT-EDIT banner shape, one
   image-grid layout, and one file-writer pair — one home per fact, no second
   copy to drift.

   HOW-public / WHAT-private: this ns is the generic HOW (a GFM writer), lives
   in protogen, and is consumed off the classpath by private consumers; it never
   carries any consumer's content. GFM only — the F2 buy-before-build survey
   found pipe tables + image refs are the whole surface a DO-NOT-EDIT page needs,
   and a templating dep would hide the byte shape the page keeps visible. Shapes
   are hand-validated (no malli dependency; the devcards tool is malli-free)."
  (:require [clojure.java.io :as io]
            [clojure.string :as str])
  (:import (java.io File)))

(set! *warn-on-reflection* true)

(defn do-not-edit-header
  "Assemble the GENERATED / DO-NOT-EDIT HTML-comment banner every generated doc
   page carries. `regen-cmd` names the exact command (plus any tool-relative
   context prose) that regenerates the page; `sources` names the inputs it is
   rendered from. Both may embed literal newlines (hand-wrapped prose). Returns
   the banner text with a trailing blank line, ready to prepend to a page body.
   The banner attributes generation to the devcards gallery generator — the tool
   family this ns belongs to — so a consumer reusing it stays honestly named."
  ^String [^String regen-cmd ^String sources]
  (str "<!--\nGENERATED by the devcards gallery generator — DO NOT EDIT.\n"
       "Regenerate: " regen-cmd ". Sources: " sources ".\n-->\n\n"))

(defn- esc-cell
  "Escape a GFM table cell: pipes break column alignment, literal newlines
   break the row."
  ^String [v]
  (-> (str v)
      (str/replace "|" "\\|")
      (str/replace "\n" " ")))

(defn md-table
  "Render `headers` + `rows` (seqs of cell values, uniform width) as a GFM pipe
   table. Headers must be REAL — a blank header cell throws (the F2 index-grid
   defect, pinned). Rows must match the header width."
  ^String [headers rows]
  (when (or (empty? headers) (some #(str/blank? (str %)) headers))
    (throw (ex-info "md-table requires a real, non-blank header row"
                    {:headers (vec headers)})))
  (doseq [row rows]
    (when (not= (count row) (count headers))
      (throw (ex-info "md-table row width != header width"
                      {:headers (vec headers) :row (vec row)}))))
  (let [line (fn [cells] (str "| " (str/join " | " (map esc-cell cells)) " |"))]
    (str/join "\n"
              (concat [(line headers)
                       (str "|" (str/join "|" (repeat (count headers) "---")) "|")]
                      (map line rows)))))

(defn image-grid-md
  "A caption × render-set image grid as a GFM table: one ROW per grid entry (its
   caption in column one, headed by `caption-header` — defaults to \"state\",
   the widget-gallery vocabulary — then one thumbnail per render set).
   `render-sets` is a seq of maps each carrying :title (the column header) +
   :file-suffix (the key into a row's :imgs map). `rows` are maps {:label
   <caption> :imgs {<suffix> <filename>}}. Each image cell is a colocated
   relative-path markdown image; the caption is real markdown text welded to
   its images by the table row, so it can never float from its card and no
   in-repo packing can misplace it."
  (^String [render-sets rows] (image-grid-md "state" render-sets rows))
  (^String [caption-header render-sets rows]
   (md-table (into [caption-header] (map :title) render-sets)
             (for [{:keys [label imgs]} rows]
               (into [(str "`" label "`")]
                     (map (fn [fam]
                            (let [f (get imgs (:file-suffix fam))]
                              (str "![" label " " (:file-suffix fam) "](./" f ")")))
                          render-sets))))))

(defn write-bytes!
  "Write `content` bytes at `path` (parent dirs created). Returns {:path
   :bytes}."
  [^String path ^bytes content]
  (io/make-parents path)
  (with-open [out (io/output-stream path)] (.write out content))
  {:path path :bytes (alength content)})

(defn write-text!
  "Write `text` at `path` (parent dirs created). Returns {:path :bytes}."
  [^String path ^String text]
  (io/make-parents path)
  (spit path text)
  {:path path :bytes (.length (File. path))})
