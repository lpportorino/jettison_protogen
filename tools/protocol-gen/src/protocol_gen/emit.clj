(ns protocol-gen.emit
  "Emitters: a resolved projection -> `.proto` text. Pure data->string.

   THE ONE PROPERTY THIS NAMESPACE EXISTS TO GUARANTEE. A field's wire number
   arrives here already stamped, in `:number`, and NOTHING in this file can
   compute one: no emitter takes an index, none of them counts, and the
   collection functions used are `map` and `sort-by` rather than
   `map-indexed`. That is the whole defence against positional numbering, and
   it is structural rather than a convention — if a number could be derived
   from position, removing one grant would renumber every field after it and
   each group's schema would stay internally consistent while disagreeing with
   every other. Nothing downstream can see that.

   `protocol-gen.numbering` is the only producer of a number for a
   locally-minted field, and it throws on an unpinned one; a
   database-sourced field carries the descriptor's own number. Both are
   asserted present before anything here runs.

   SHAPE, DELIBERATELY DUMB. Layout favours a deterministic, diffable emission
   over hand-formatting: the file is fed through `buf format` where that tool
   is available, and buf owns the final layout. This mirrors
   `lvgl-codegen.construct.emit`, the enum-only `.proto` emitter this
   repository already carries, rather than inventing a second shape."
  (:require [clojure.string :as str]
            [malli.core :as m]))

(set! *warn-on-reflection* true)

(def banner
  "The header every emitted file carries. A generated projection that does not
   say so invites a hand edit that the next run silently destroys."
  (str "// GENERATED by protocol-gen — DO NOT EDIT.\n"
       "// Source of truth: the descriptor database, the access policy, and the\n"
       "// assign-once field-number registry named in this run's arguments.\n"
       "// Every field number here is the descriptor's or the registry's; none\n"
       "// is derived from position.\n"))

(def emitted-field
  "One field, fully resolved: its emitted proto type is a STRING by the time it
   reaches here, so this namespace needs no database and cannot resolve — or
   mis-resolve — a reference.

   `:number` is REQUIRED and has no default. That is the point: a field with no
   number cannot be built, so it cannot be emitted with an invented one."
  [:map {:closed true}
   [:name [:string {:min 1}]]
   [:number [:int {:min 1}]]
   [:proto-type [:string {:min 1}]]
   [:repeated :boolean]
   [:oneof [:maybe [:string {:min 1}]]]
   [:options [:vector [:string {:min 1}]]]])

(def emitted-oneof
  "One oneof declaration on an emitted message."
  [:map {:closed true}
   [:name [:string {:min 1}]]
   [:required :boolean]])

(def emitted-message
  "One emitted message."
  [:map {:closed true}
   [:proto-name [:string {:min 1}]]
   [:fields [:vector emitted-field]]
   [:oneofs [:vector emitted-oneof]]])

(def emitted-enum
  "One emitted enum. Values carry their own numbers for the same reason fields
   do — a proto3 enum's zero member is pinned by the LANGUAGE, and every other
   member's number is the source's."
  [:map {:closed true}
   [:proto-name [:string {:min 1}]]
   [:values [:vector [:map {:closed true}
                      [:name [:string {:min 1}]]
                      [:number :int]]]]])

(def emitted-file
  "One emitted `.proto` file."
  [:map {:closed true}
   [:package [:string {:min 1}]]
   [:imports [:vector [:string {:min 1}]]]
   [:enums [:vector emitted-enum]]
   [:messages [:vector emitted-message]]])

(defn- option-suffix
  "The `[opt, opt]` tail of a field line, or nil when the field carries no
   options.

   NIL RATHER THAN THE EMPTY STRING so the return position can say something:
   `str` renders nil as nothing, and `[:maybe [:string {:min 1}]]` is a shape a
   reader learns from where a bare `:string` would admit the empty string as a
   meaningful value it never is."
  [options]
  (when (seq options)
    (str " [" (str/join ", " options) "]")))

(m/=> option-suffix
      [:=> [:cat [:vector [:string {:min 1}]]] [:maybe [:string {:min 1}]]])

(defn field->proto
  "One field line, indented by `indent` spaces.

   Reads `:number` and never a position. The argument list carries no index and
   the body creates none."
  [indent {:keys [number proto-type repeated options] field-name :name}]
  (str (apply str (repeat indent \space))
       (when repeated "repeated ")
       proto-type " " field-name " = " number (option-suffix options) ";"))

(m/=> field->proto [:=> [:cat [:int {:min 0}] emitted-field] [:string {:min 1}]])

(defn- oneof->proto
  "One `oneof` block: its required option when the source declared it, then its
   member fields in NUMBER order."
  [{:keys [required] oneof-name :name} members]
  (str "  oneof " oneof-name " {\n"
       (when required "    option (buf.validate.oneof).required = true;\n")
       (str/join "\n" (map #(field->proto 4 %) (sort-by :number members)))
       "\n  }"))

(m/=> oneof->proto
      [:=> [:cat emitted-oneof [:sequential emitted-field]] [:string {:min 1}]])

(defn message->proto
  "One `message` block.

   Free fields first in NUMBER order, then one block per oneof, the blocks
   ordered by their lowest member number. Both orderings are by number, so the
   emitted layout is a function of the wire contract rather than of the order
   anything happened to be built in — which is what makes two runs over the
   same inputs byte-identical.

   A oneof whose members were all withheld by the policy emits no block at all;
   an empty `oneof` is not legal proto and a projection is entitled to grant a
   subset of a oneof's arms."
  [{:keys [proto-name fields oneofs]}]
  (let [by-oneof (group-by :oneof fields)
        free (sort-by :number (get by-oneof nil))
        blocks (->> oneofs
                    (keep (fn [o]
                            (when-let [members (seq (get by-oneof (:name o)))]
                              [(reduce min (map :number members))
                               (oneof->proto o members)])))
                    (sort-by first)
                    (map second))
        body (concat (map #(field->proto 2 %) free) blocks)]
    (str "message " proto-name " {"
         (when (seq body) (str "\n" (str/join "\n" body) "\n"))
         "}\n")))

(m/=> message->proto [:=> [:cat emitted-message] [:string {:min 1}]])

(defn enum->proto
  "One `enum` block, members in NUMBER order."
  [{:keys [proto-name values]}]
  (str "enum " proto-name " {\n"
       (str/join "\n"
                 (for [{:keys [number] value-name :name} (sort-by :number values)]
                   (str "  " value-name " = " number ";")))
       "\n}\n"))

(m/=> enum->proto [:=> [:cat emitted-enum] [:string {:min 1}]])

(defn file->proto
  "The whole emitted `.proto` text for one group.

   Imports, enums and messages are each emitted in sorted order so the output
   is a pure function of its input set. Nothing here decides WHAT is emitted —
   that was settled by the policy two passes earlier."
  [{:keys [package imports enums messages]}]
  (str banner
       "\nsyntax = \"proto3\";\n\npackage " package ";\n"
       (when (seq imports)
         (str "\n" (str/join "\n" (for [i (sort imports)] (str "import \"" i "\";"))) "\n"))
       (when (seq enums)
         (str "\n" (str/join "\n" (map enum->proto (sort-by :proto-name enums)))))
       (when (seq messages)
         (str "\n" (str/join "\n" (map message->proto (sort-by :proto-name messages)))))))

(m/=> file->proto [:=> [:cat emitted-file] [:string {:min 1}]])
