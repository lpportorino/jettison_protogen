(ns devcards.docgen-test
  "Unit tests for the generic Markdown doc-gen primitives in `devcards.docgen`
   (extracted from devcards.docs so the widget gallery + private consumers share
   one home). These PIN EXISTING behavior — md-table's two throw contracts, the
   image-grid layout, and the DO-NOT-EDIT banner's byte shape — the behavior the
   byte-identical gallery re-mint proves end-to-end. `write-text!`/`write-bytes!`
   are exercised by that same re-mint (they write every committed page + JPEG),
   so they carry no separate unit test here."
  (:require [clojure.test :refer [deftest is testing]]
            [devcards.docgen :as docgen]))

;; ── md-table ────────────────────────────────────────────────────────────
(deftest md-table-happy-path
  (testing "header row + GFM separator + one line per row, pipe-delimited"
    (is (= "| a | b |\n|---|---|\n| 1 | 2 |\n| 3 | 4 |"
           (docgen/md-table ["a" "b"] [["1" "2"] ["3" "4"]])))))

(deftest md-table-escapes-cells
  (testing "a pipe is backslash-escaped and a newline collapses to a space, so
            neither breaks the row/column structure"
    (is (= "| a |\n|---|\n| x\\|y |\n| p q |"
           (docgen/md-table ["a"] [["x|y"] ["p\nq"]])))))

(deftest md-table-rejects-empty-headers
  (testing "no header row at all throws (the F2 index-grid defect, pinned)"
    (is (thrown-with-msg? clojure.lang.ExceptionInfo #"non-blank header row"
                          (docgen/md-table [] [["1"]])))))

(deftest md-table-rejects-blank-header-cell
  (testing "a blank header cell throws — a real header row is the contract"
    (is (thrown-with-msg? clojure.lang.ExceptionInfo #"non-blank header row"
                          (docgen/md-table ["a" ""] [["1" "2"]])))
    (is (thrown-with-msg? clojure.lang.ExceptionInfo #"non-blank header row"
                          (docgen/md-table ["a" "   "] [["1" "2"]])))))

(deftest md-table-rejects-row-width-mismatch
  (testing "a row whose width differs from the header throws (no silent ragged
            table)"
    (is (thrown-with-msg? clojure.lang.ExceptionInfo #"row width"
                          (docgen/md-table ["a" "b"] [["only-one"]])))
    (is (thrown-with-msg? clojure.lang.ExceptionInfo #"row width"
                          (docgen/md-table ["a"] [["a" "b"]])))))

;; ── image-grid-md ───────────────────────────────────────────────────────
(deftest image-grid-md-shape
  (testing "one caption column + one image column per render set; each image
            cell is a colocated relative-path markdown image keyed by :file-suffix"
    (is (= (str "| state | dark | light |\n"
                "|---|---|---|\n"
                "| `main` | ![main dark](./d.jpg) | ![main light](./l.jpg) |")
           (docgen/image-grid-md
            [{:title "dark" :file-suffix "dark"} {:title "light" :file-suffix "light"}]
            [{:label "main" :imgs {"dark" "d.jpg" "light" "l.jpg"}}])))))

(deftest image-grid-md-one-row-per-entry
  (testing "each :label becomes its own table row, in order"
    (is (= (str "| state | v |\n"
                "|---|---|\n"
                "| `a` | ![a v](./a.jpg) |\n"
                "| `b` | ![b v](./b.jpg) |")
           (docgen/image-grid-md
            [{:title "v" :file-suffix "v"}]
            [{:label "a" :imgs {"v" "a.jpg"}}
             {:label "b" :imgs {"v" "b.jpg"}}])))))

(deftest image-grid-md-caption-header
  (testing "the caption column header is parameterizable; the 2-arity keeps
            the widget-gallery \"state\" default"
    (is (= (str "| screen | v |\n"
                "|---|---|\n"
                "| `a` | ![a v](./a.jpg) |")
           (docgen/image-grid-md
            "screen"
            [{:title "v" :file-suffix "v"}]
            [{:label "a" :imgs {"v" "a.jpg"}}])))
    (is (.startsWith
         ^String (docgen/image-grid-md [{:title "v" :file-suffix "v"}]
                                       [{:label "a" :imgs {"v" "a.jpg"}}])
         "| state | v |"))))

;; ── do-not-edit-header ──────────────────────────────────────────────────
(deftest do-not-edit-header-byte-shape
  (testing "the banner frame is fixed; regen-cmd + sources fill the two slots,
            newlines they embed are preserved, trailing blank line included"
    (is (= (str "<!--\n"
                "GENERATED by the devcards gallery generator — DO NOT EDIT.\n"
                "Regenerate: REGEN. Sources: SRC.\n"
                "-->\n\n")
           (docgen/do-not-edit-header "REGEN" "SRC")))
    (is (= (str "<!--\n"
                "GENERATED by the devcards gallery generator — DO NOT EDIT.\n"
                "Regenerate: line1\nline2. Sources: srcA\nsrcB.\n"
                "-->\n\n")
           (docgen/do-not-edit-header "line1\nline2" "srcA\nsrcB")))))
