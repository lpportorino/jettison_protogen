/// Monotonic event_time (ms) for px-driven pointer events. Each call steps a
/// few ms — enough to be strictly increasing (the FSM clock) yet far under the
/// 2500ms stale-GC window, so a settled drag never self-cancels.
fn next_event_time() -> u64 {
    use std::sync::atomic::{AtomicU64, Ordering};
    static CLOCK: AtomicU64 = AtomicU64::new(1000);
    CLOCK.fetch_add(5, Ordering::Relaxed)
}
/// Press pointer id 1 at framebuffer px `(x, y)` (the R4 DOWN phase).
fn press_px(host: &mut ControlsHost, x: i32, y: i32) {
    let (nx, ny) = px_to_ndc(x, y);
    host.pointer(lvgl_harness::PointerEvent::down(
        1,
        nx,
        ny,
        next_event_time(),
    ))
    .expect("pointer down");
}
/// Move pointer id 1 to framebuffer px `(x, y)` (the R4 MOVE phase).
fn move_px(host: &mut ControlsHost, x: i32, y: i32) {
    let (nx, ny) = px_to_ndc(x, y);
    host.pointer(lvgl_harness::PointerEvent::mv(1, nx, ny, next_event_time()))
        .expect("pointer move");
}
/// Release pointer id 1 at framebuffer px `(x, y)` (the R4 UP phase).
fn release_px(host: &mut ControlsHost, x: i32, y: i32) {
    let (nx, ny) = px_to_ndc(x, y);
    host.pointer(lvgl_harness::PointerEvent::up(1, nx, ny, next_event_time()))
        .expect("pointer up");
}
