//! Visual regression tests for the LVGL controls WASM renderer.
//!
//! Loads pre-generated `.pb` fixtures, renders them via the WASM `ControlsHost`,
//! and verifies rendered content using both pixel-diff and CV-based analysis.
//!
//! # Test Categories
//!
//! - **per_widget**: each of 18 widget types renders a non-empty framebuffer
//! - **class_reorder_invariance**: reordering class tokens produces identical output
//! - **class_modification**: adding a visual class changes the rendered image
//! - **value_change**: different widget prop values produce different images
//! - **composite**: nested widget hierarchies render correctly
//! - **theme**: dark vs light theme produces different output, with color verification
//! - **font_loading**: custom fonts render with correct text color
//! - **boundary_contracts**: wrong-oneof-slot style values reject the load;
//!   bare-root labels render glyphs identical to themed roots (a=255 set)
//! - **host_event_envelope**: the named-event JSON envelope lane (`host_event`,
//!   ABI v2) — closed six-key contract, hostile-name escaping, consecutive
//!   `seq`, relay gating, and byte-unchanged coexistence with the cmd wire
