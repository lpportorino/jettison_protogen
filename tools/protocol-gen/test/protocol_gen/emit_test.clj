(ns protocol-gen.emit-test
  (:require [clojure.string :as str]
            [clojure.test :refer [deftest is testing]]
            [protocol-gen.emit :as emit]))

(defn- fld
  [nm n t & {:keys [repeated oneof options]}]
  {:name nm :number n :proto-type t
   :repeated (boolean repeated) :oneof oneof :options (vec options)})

(deftest field-line-carries-the-number-it-was-given
  (testing "the number in the text is the number in the field, not its position"
    ;; The vector order is deliberately the REVERSE of the number order, and
    ;; the numbers are deliberately not 1 and 2. A positional emitter passes a
    ;; test whose fixture is numbered 1..n in order; this one it cannot.
    (let [msg {:proto-name "M"
               :fields [(fld "later" 7 "double") (fld "earlier" 3 "int32")]
               :oneofs []}
          out (emit/message->proto msg)]
      (is (str/includes? out "double later = 7;"))
      (is (str/includes? out "int32 earlier = 3;"))
      (is (not (str/includes? out "= 1;")))
      (is (not (str/includes? out "= 2;")))
      (testing "and the lines come out in NUMBER order, not vector order"
        (is (< (str/index-of out "earlier") (str/index-of out "later")))))))

(deftest repeated-and-options-render
  (is (= "  repeated string tags = 4;"
         (emit/field->proto 2 (fld "tags" 4 "string" :repeated true))))
  (is (= "  int32 a = 1 [(buf.validate.field).int32 = {gte: 0}];"
         (emit/field->proto 2 (fld "a" 1 "int32"
                                   :options ["(buf.validate.field).int32 = {gte: 0}"]))))
  (testing "two options are comma-separated inside one bracket"
    (is (= "  int32 a = 1 [x, y];"
           (emit/field->proto 2 (fld "a" 1 "int32" :options ["x" "y"]))))))

(deftest oneof-blocks-are-emitted-around-their-members
  (let [msg {:proto-name "Root"
             :fields [(fld "free" 9 "bool")
                      (fld "stop" 2 "Stop" :oneof "cmd")
                      (fld "start" 1 "Start" :oneof "cmd")]
             :oneofs [{:name "cmd" :required true}]}
        out (emit/message->proto msg)]
    (is (str/includes? out "oneof cmd {"))
    (is (str/includes? out "option (buf.validate.oneof).required = true;"))
    (is (str/includes? out "    Start start = 1;"))
    (is (str/includes? out "    Stop stop = 2;"))
    (testing "free fields precede the oneof block"
      (is (< (str/index-of out "bool free") (str/index-of out "oneof cmd"))))
    (testing "members are ordered by number inside the block"
      (is (< (str/index-of out "Start start") (str/index-of out "Stop stop"))))))

(deftest a-oneof-with-no-granted-members-emits-no-block
  ;; An empty `oneof` is not legal proto, and a policy is entitled to grant a
  ;; subset of a oneof's arms — including none of them.
  (let [out (emit/message->proto {:proto-name "Root"
                                  :fields [(fld "free" 1 "bool")]
                                  :oneofs [{:name "cmd" :required true}]})]
    (is (not (str/includes? out "oneof")))))

(deftest an-empty-message-emits-a-legal-empty-block
  (is (= "message Empty {}\n"
         (emit/message->proto {:proto-name "Empty" :fields [] :oneofs []}))))

(deftest enum-members-are-emitted-in-number-order-with-their-own-numbers
  (let [out (emit/enum->proto {:proto-name "E"
                               :values [{:name "E_B" :number 5} {:name "E_A" :number 0}]})]
    (is (str/includes? out "E_A = 0;"))
    (is (str/includes? out "E_B = 5;"))
    (is (< (str/index-of out "E_A") (str/index-of out "E_B")))))

(deftest file-emission-is-deterministic-and-sorted
  (let [f {:package "grp.a"
           :imports ["buf/validate/validate.proto"]
           :enums [{:proto-name "Z" :values [{:name "Z_U" :number 0}]}
                   {:proto-name "A" :values [{:name "A_U" :number 0}]}]
           :messages [{:proto-name "Zed" :fields [] :oneofs []}
                      {:proto-name "Alpha" :fields [] :oneofs []}]}
        out (emit/file->proto f)]
    (is (str/starts-with? out "// GENERATED by protocol-gen"))
    (is (str/includes? out "syntax = \"proto3\";"))
    (is (str/includes? out "package grp.a;"))
    (is (str/includes? out "import \"buf/validate/validate.proto\";"))
    (testing "enums and messages come out sorted by name"
      (is (< (str/index-of out "enum A ") (str/index-of out "enum Z ")))
      (is (< (str/index-of out "message Alpha") (str/index-of out "message Zed"))))
    (testing "two emissions of the same input are byte-identical"
      (is (= out (emit/file->proto f))))))

(deftest a-file-with-nothing-in-it-still-emits-a-header
  (is (str/includes? (emit/file->proto {:package "grp.empty" :imports []
                                        :enums [] :messages []})
                     "package grp.empty;")))
