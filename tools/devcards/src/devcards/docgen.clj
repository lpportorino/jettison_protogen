(ns devcards.docgen
  "Generic Markdown doc-gen primitives shared by the devcards gallery generator
   (devcards.docs — the committed public per-widget pages) and any consumer that
   dogfoods the same documentation axis over its own render set (asgard's
   private screen-corpus docs). Extracted verbatim from devcards.docs so BOTH
   producers share one GFM table builder, one DO-NOT-EDIT banner shape, one
   image-grid layout, and one file-writer pair — one home per fact, no second
   copy to drift.

   HOW-public / WHAT-private: this ns is the generic HOW (a GFM writer), lives
   in protogen, and is consumed off the classpath by private consumers; it never
   carries any consumer's content. GFM only — the F2 buy-before-build survey
   found pipe tables + image refs are the whole surface a DO-NOT-EDIT page needs,
   and a templating dep would hide the byte shape the page keeps visible. Shapes
   are hand-validated (no malli dependency; the devcards tool is malli-free)."
  (:require [clojure.java.io :as io]
            [clojure.string :as str]
            [devcards.corpus :as corpus])
  (:import (java.io File)))

(set! *warn-on-reflection* true)

(defn do-not-edit-header
  "Assemble the GENERATED / DO-NOT-EDIT HTML-comment banner every generated doc
   page carries. `regen-cmd` names the exact command (plus any tool-relative
   context prose) that regenerates the page; `sources` names the inputs it is
   rendered from. Both may embed literal newlines (hand-wrapped prose). Returns
   the banner text with a trailing blank line, ready to prepend to a page body.
   The banner attributes generation to the devcards gallery generator — the tool
   family this ns belongs to — so a consumer reusing it stays honestly named."
  ^String [^String regen-cmd ^String sources]
  (str "<!--\nGENERATED by the devcards gallery generator — DO NOT EDIT.\n"
       "Regenerate: " regen-cmd ". Sources: " sources ".\n-->\n\n"))

(defn- esc-cell
  "Escape a GFM table cell: pipes break column alignment, literal newlines
   break the row."
  ^String [v]
  (-> (str v)
      (str/replace "|" "\\|")
      (str/replace "\n" " ")))

(defn md-table
  "Render `headers` + `rows` (seqs of cell values, uniform width) as a GFM pipe
   table. Headers must be REAL — a blank header cell throws (the F2 index-grid
   defect, pinned). Rows must match the header width."
  ^String [headers rows]
  (when (or (empty? headers) (some #(str/blank? (str %)) headers))
    (throw (ex-info "md-table requires a real, non-blank header row"
                    {:headers (vec headers)})))
  (doseq [row rows]
    (when (not= (count row) (count headers))
      (throw (ex-info "md-table row width != header width"
                      {:headers (vec headers) :row (vec row)}))))
  (let [line (fn [cells] (str "| " (str/join " | " (map esc-cell cells)) " |"))]
    (str/join "\n"
              (concat [(line headers)
                       (str "|" (str/join "|" (repeat (count headers) "---")) "|")]
                      (map line rows)))))

(defn image-grid-md
  "A caption × render-set image grid as a GFM table: one ROW per grid entry (its
   caption in column one, headed by `caption-header` — defaults to \"state\",
   the widget-gallery vocabulary — then one thumbnail per render set).
   `render-sets` is a seq of maps each carrying :title (the column header) +
   :file-suffix (the key into a row's :imgs map). `rows` are maps {:label
   <caption> :imgs {<suffix> <filename>}}. Each image cell is a colocated
   relative-path markdown image; the caption is real markdown text welded to
   its images by the table row, so it can never float from its card and no
   in-repo packing can misplace it."
  (^String [render-sets rows] (image-grid-md "state" render-sets rows))
  (^String [caption-header render-sets rows]
   (md-table (into [caption-header] (map :title) render-sets)
             (for [{:keys [label imgs]} rows]
               (into [(str "`" label "`")]
                     (map (fn [fam]
                            (let [f (get imgs (:file-suffix fam))]
                              (str "![" label " " (:file-suffix fam) "](./" f ")")))
                          render-sets))))))

(defn audit
  "TWO-WAY disk reconciliation for a generated tree: what the emitter CLAIMS
   it wrote, against what is actually on disk under `root`.

   WHY IT EXISTS. A doc emitter here only ever WRITES. Retire a widget, a
   sink or a lego from the corpus and the generator simply stops emitting that
   unit's files, which leaves them on disk, TRACKED, and byte-unchanged. A
   freshness gate shaped `git diff --exit-code <root>` then reports nothing
   about them, because nothing modified them: the author commits the re-mint,
   and from that commit on every run is green with the orphans still shipping
   to every consumer that clones this history. Measured on this tree —
   retiring one composition card left three tracked JPEGs behind and the
   freshness step exited 0.

   THIS FN STAYS NON-DESTRUCTIVE, and that is a boundary rather than an
   omission. `prune-orphans!` below adds the deletion, and it can only do so
   because it is handed a TOTALITY PRECONDITION and a naming policy that say
   which absences are retirements. This one is also the reconciliation for the
   goldens tree and the composition scratch tree, where no such precondition
   exists and where the correct answer to an orphan is a blocking finding.
   Do not move a delete in here.

   No other lane can see it, and for one shared reason: the devcard gate
   judges cards that EXIST, the golden manifests hash cards that EXIST, and
   the freshness diff compares files that are WRITTEN. All three are keyed
   on the LIVE corpus, and an orphan is precisely what has left it.

   BOTH DIRECTIONS ARE REPORTED. :missing is claimed-but-absent (a write
   that silently failed, or a root pointed at the wrong tree); :orphaned is
   present-but-unclaimed (the retired unit). Reporting one would trade one
   blind spot for the other. Returns {:root :claimed :missing :orphaned},
   both vectors sorted.

   `claimed` must be the emitter's OWN report of the paths it wrote — pass
   `(map :path files)` straight from the `write-text!` / `write-bytes!`
   returns. A hand-listed inventory would be a second home for the naming
   scheme and would go stale in exactly the way this audit exists to catch:
   the same defect, one level up.

   Three refusals, because each silence would read as a clean tree:
   - a root that is not a directory THROWS. An absent root walks to nothing,
     which reports zero orphans — indistinguishable from a reconciled tree.
   - an EMPTY claim throws. Empty against empty otherwise reports both
     directions clean while proving only that the emitter wrote nothing.
   - a DUPLICATED claimed path throws. Two units claiming one path means one
     silently overwrote the other, and the set arithmetic below would call
     that reconciled.

   Compares CANONICAL paths, so a claimed \"docs/x.jpg\" and a walked
   \"./docs/x.jpg\" are one path rather than a missing/orphaned pair. Only
   FILES are walked: git tracks no directories, so an emptied directory
   cannot reach a consumer's clone.

   The set comparison delegates to `devcards.corpus/diff-cards`, the existing
   committed-vs-rendered reconciliation. Canonical paths are the identities
   and both sides carry one constant presence hash. Its :missing and
   :unexpected classes therefore become this fn's :missing and :orphaned;
   :mismatched is impossible by construction because artifact CONTENT is not
   this audit's contract."
  [^String root claimed]
  (let [dir (File. root)]
    (when-not (.isDirectory dir)
      (throw (ex-info (str "audit root " (pr-str root) " is not a directory — "
                           "an absent root walks to nothing and reports zero "
                           "orphans, which is byte-identical to a reconciled "
                           "tree")
                      {:root root})))
    (let [claimed-paths (mapv #(.getCanonicalPath (File. ^String %)) claimed)]
      (when (empty? claimed-paths)
        (throw (ex-info (str "the emitter claimed ZERO paths — an empty claim "
                             "against an empty tree would pass without proving "
                             "that the emitter wrote anything")
                        {:root root :claimed 0})))
      (let [claimed-set (set claimed-paths)]
        (when (not= (count claimed-set) (count claimed-paths))
          (throw (ex-info (str "the emitter claimed the SAME canonical path "
                               "twice — one unit overwrote another's file, and "
                               "reconciling the deduped set against disk would "
                               "report that as clean")
                          {:root root
                           :claimed (count claimed-paths)
                           :duplicated
                           (vec (sort (for [[p n] (frequencies claimed-paths)
                                            :when (> n 1)]
                                        p)))})))
        (let [on-disk (into #{}
                            (comp (filter #(.isFile ^File %))
                                  (map #(.getCanonicalPath ^File %)))
                            (file-seq dir))
              as-cards (fn [paths]
                         (into {} (map (fn [p] [p {:sha256 ::present}])) paths))
              {:keys [mismatched missing unexpected]}
              (corpus/diff-cards (as-cards claimed-set) (as-cards on-disk))]
          (when (seq mismatched)
            (throw (ex-info "artifact-presence comparison produced content drift"
                            {:root root :mismatched mismatched})))
          {:root root
           :claimed (count claimed-set)
           :missing missing
           :orphaned unexpected})))))

(defn- canonical
  "A path's canonical form — the identity `audit` reconciles on, so the
   pruner's own set arithmetic cannot disagree with the walk it prunes."
  ^String [^String p]
  (.getCanonicalPath (File. p)))

(defn prune-orphans!
  "DELETE the orphans a generated root has accumulated; REPORT everything else.

   `audit` above reports both directions and removes nothing, which leaves a
   retired artifact TRACKED until a human reads the finding and runs `git rm`.
   This is the same reconciliation with one destructive step attached, and it
   has to answer the question the audit never had to: an orphan is `absent
   from the claim`, and ABSENT FROM THE CLAIM is what a retired unit and a
   unit this run never rendered look like ALIKE. Delete on the wrong reading
   and a single bad run takes the whole tree with it.

   THE TOTALITY PRECONDITION IS HOW THEY ARE TOLD APART, and it is imposed
   HERE rather than trusted from the caller — a caller can forget, a seam
   cannot. `required-claims` is the set of paths the emitter DECLARES it must
   have written for this run to be complete, and it only means anything
   because it is derived from data that does not depend on the render (for the
   widget gallery: one page per unit of the enum-derived registry, resolved
   before a single pixel). Then:

   - every required claim present in `claimed` → the run rendered its whole
     DECLARED set, so an artifact absent from it is RETIRED. Delete the ones
     `disposition` authorises.
   - any required claim missing → the run is PARTIAL. Delete NOTHING: every
     orphan is returned kept with reason `:run-not-total`, and the caller's
     audit reports the lot exactly as it did before this fn existed.

   It fails, in other words, in the direction that KEEPS FILES. That is also
   why the precondition may not be empty: a precondition requiring nothing is
   satisfied by a run that rendered nothing, which is precisely the partial
   run whose orphans must not be deleted.

   THIS IS THE SECOND LINE OF DEFENCE, NOT THE FIRST. A generator worth
   pruning behind is already total — the widget gallery throws on a class with
   zero built cards, on sinks disagreeing with the spec, on a composition
   build disagreeing with its inventory, on a unit with no preview, on a
   declared page the renderer did not produce — so a partial claim should
   never reach here at all. The precondition exists for the refactor that
   loosens one of those throws without anyone noticing that a deletion now
   hangs off it.

   `disposition` decides WHAT MAY GO, and it is deliberately not a boolean: it
   returns `:retired` to authorise deletion, or any other keyword as the
   REASON the path is being kept, so `:kept` is self-describing and a rule
   that declines cannot be confused with a rule that never looked. Widening is
   its own hazard, so two limits are enforced here regardless of what it
   returns: a non-keyword answer throws, and an authorised path that does not
   lie strictly under `root` throws rather than being deleted.

   Deletion is FILES only, inherited from `audit`'s walk. An emptied unit
   directory is left behind: git tracks no directories, so it cannot reach a
   consumer's clone, and removing it would be exactly the silent widening the
   `disposition` contract above exists to prevent.

   EVERY REFUSAL HERE FIRES BEFORE THE FIRST `.delete`, and that ordering is
   load-bearing rather than incidental: it is what lets `run-prune!` below
   absorb a refusal into a value, knowing the value describes a tree nothing
   has touched. Keep the delete step last.

   `opts` = {:root :claimed :required-claims :disposition}. Returns
   {:root :claimed :missing :deleted :undeletable :kept :unmet :refused :line}.
   `:undeletable` is a delete the filesystem refused; it is left for the
   caller's audit to re-report as an orphan, which is why this fn does not
   throw on one — the tree is still exactly as reconcilable as it was."
  [{:keys [^String root claimed required-claims disposition]}]
  (when-not (ifn? disposition)
    (throw (ex-info (str "prune-orphans! needs a disposition fn — without one "
                         "nothing decides what may be deleted")
                    {:root root :disposition (type disposition)
                     :prune/contract true})))
  (let [required (into (sorted-set) (map canonical) required-claims)]
    (when (empty? required)
      (throw (ex-info (str "prune-orphans! was handed an EMPTY totality "
                           "precondition — a precondition that requires nothing "
                           "is satisfied by a run that rendered nothing, which "
                           "is the partial run whose orphans must not be deleted")
                      {:root root :prune/contract true})))
    (let [a (audit root claimed)
          claimed-set (into #{} (map canonical) claimed)
          unmet (vec (remove claimed-set required))
          root-prefix (str (canonical root) File/separator)
          judged (mapv (fn [^String p] [p (disposition p)]) (:orphaned a))
          _ (doseq [[^String p d] judged]
              (when-not (keyword? d)
                (throw (ex-info (str "a disposition must answer with a keyword — "
                                     ":retired to authorise deletion, or the "
                                     "reason the path is kept")
                                {:root root :path p :disposition d
                                 :prune/contract true})))
              (when (and (= :retired d) (not (str/starts-with? p root-prefix)))
                (throw (ex-info (str "the disposition authorised deleting a path "
                                     "OUTSIDE the audited root — a prune may never "
                                     "reach past the tree it reconciled")
                                {:root root :path p :prune/contract true}))))
          total? (empty? unmet)
          authorised (if total?
                       (vec (sort (for [[p d] judged :when (= :retired d)] p)))
                       [])
          kept (vec (sort-by :path
                             (for [[p d] judged
                                   :when (or (not total?) (not= :retired d))]
                               {:path p :reason (if total? d :run-not-total)})))
          deleted (filterv #(.delete (File. ^String %)) authorised)
          undeletable (vec (remove (set deleted) authorised))]
      {:root root
       :claimed (:claimed a)
       :missing (:missing a)
       :deleted deleted
       :undeletable undeletable
       :kept kept
       :unmet unmet
       :refused (when-not total?
                  (str "the run did not write " (count unmet) " of its "
                       (count required) " DECLARED pages, so every orphan was "
                       "kept: an incomplete run's absences are not retirements"))
       :line (format (str "doc-prune: root %s | %s | deleted %d | kept %d | "
                          "undeletable %d")
                     root
                     (if total? "run TOTAL" (format "run PARTIAL (%d unmet)" (count unmet)))
                     (count deleted)
                     (count kept)
                     (count undeletable))})))

(defn run-prune!
  "TOTAL adapter for a CLI arm, mirroring `run-audit` below: run
   `prune-orphans!` and return a designed refusal as a VALUE rather than a
   throw.

   IT MUST NOT BECOME A NEW WAY TO KILL THE RUN. Every refusal
   `prune-orphans!` raises is also a condition the caller's own `run-audit`
   over the same root meets moments later, where it already becomes a
   PERSISTED blocking finding. Letting the throw escape would replace that
   report with a stack trace and discard the findings the render lanes had
   already assembled — the prune is an addition to the reporting path, never a
   subtraction from it. So it exits non-zero either way; the difference is
   whether the operator gets a findings file.

   ONLY THE TREE'S REFUSALS ARE ABSORBED. The reconciliation's three — a
   root that is not a directory, an empty claim, a duplicated claim — are
   conditions of the CALL SITE'S OWN inputs, so `run-audit` over the same root
   and the same claim meets each of them again and reports it. `prune-orphans!`
   also raises four refusals about the PRUNE CONTRACT itself — a missing or
   non-keyword `disposition`, an empty `required-claims`, an authorisation
   reaching outside the root — and nothing downstream re-derives those. Those
   carry `:prune/contract` in their ex-data and are RE-THROWN: absorbing a
   misconfigured call would print a line and let a tree with no orphans exit
   green, which is the one shape this whole file exists to refuse.

   THIS IS ONLY SAFE BECAUSE NOTHING HAS BEEN DELETED YET — see
   `prune-orphans!` on why every refusal precedes the delete step. Anything
   that is NOT a designed refusal still propagates."
  [opts]
  (try (prune-orphans! opts)
       (catch clojure.lang.ExceptionInfo e
         (when (:prune/contract (ex-data e)) (throw e))
         (let [root (:root opts)]
           {:root root
            :deleted [] :undeletable [] :kept [] :unmet [] :missing []
            :refused (ex-message e)
            :line (str "doc-prune: root " root " | REFUSED | " (ex-message e))}))))

(defn audit-findings
  "`audit`'s two directions as batch-level findings.

   These findings deliberately do NOT pass through `findings/card-findings`.
   A disk audit reconciles one whole root against the emitter's complete
   claimed set; it is neither a per-card rule nor something that can be run
   once for each card without repeating the filesystem walk. It therefore
   cannot use that function's exemption matching or producer metadata.
   `devcards.core` feeds the returned findings to `lanes/run-verdict`, so they
   do share the gate's total reporting and exit policy. `:gate :disk-audit`
   makes the batch source explicit instead of implying registry provenance.

   `details` is required and root-specific:
   {:missing string :orphaned string :refused string}. A tracked generated
   tree and a cleaned scratch tree have different recovery actions, so one
   generic prescription would be false for at least one caller."
  [{:keys [root missing orphaned]} details]
  (doseq [k [:missing :orphaned :refused]]
    (when (str/blank? (get details k))
      (throw (ex-info "audit finding details must be non-blank and root-specific"
                      {:root root :missing-detail k}))))
  (-> (mapv (fn [p]
              {:gate :disk-audit
               :card root
               :invariant :missing-artifact
               :node p
               :detail (:missing details)})
            missing)
      (into (mapv (fn [p]
                    {:gate :disk-audit
                     :card root
                     :invariant :orphaned-artifact
                     :node p
                     :detail (:orphaned details)})
                  orphaned))))

(defn run-audit
  "TOTAL adapter for a CLI arm: run `audit`, turn a designed refusal into one
   blocking finding, and return {:audit :findings :line}.

   `audit` itself keeps its throw contract for direct consumers and tests.
   The CLI uses this adapter so a non-directory root, empty claim, or duplicate
   claim joins the FULL findings vector, which `core.clj` persists before
   calling the total verdict. A refusal can therefore never discard findings
   the render lanes already produced."
  [^String root claimed details]
  (try
    (let [a (audit root claimed)]
      {:audit a
       :findings (audit-findings a details)
       :line (format "doc-audit: root %s | %d claimed | missing %d | orphaned %d"
                     (:root a)
                     (:claimed a)
                     (count (:missing a))
                     (count (:orphaned a)))})
    (catch clojure.lang.ExceptionInfo e
      (let [data (ex-data e)
            finding {:gate :disk-audit
                     :card root
                     :invariant :audit-refused
                     :detail (str (:refused details) ": " (ex-message e))}]
        {:audit (merge {:root root :refused (ex-message e)} data)
         :findings [finding]
         :line (str "doc-audit: root " root " | REFUSED | " (ex-message e))}))))

(defn write-bytes!
  "Write `content` bytes at `path` (parent dirs created). Returns {:path
   :bytes}."
  [^String path ^bytes content]
  (io/make-parents path)
  (with-open [out (io/output-stream path)] (.write out content))
  {:path path :bytes (alength content)})

(defn write-text!
  "Write `text` at `path` (parent dirs created). Returns {:path :bytes}."
  [^String path ^String text]
  (io/make-parents path)
  (spit path text)
  {:path path :bytes (.length (File. path))})
