/// T1.0b — the `vis_px` ancestor-clip visibility metric: a node whose box is
/// partially clipped away by an ancestor (or the display) carries
/// `"vis_px":<visible-area-px>`; a fully-visible node carries NOTHING
/// (emit-only-when-it-differs, like every other dump field). Zero visible
/// area is the devcard invariant lane's occlusion signal.
mod dump_vis_px {
    use super::*;
    fn parsed(host: &mut ControlsHost) -> serde_json::Value {
        let dump = host.dump_tree().expect("dump_tree");
        serde_json::from_str(&dump).expect("dump parses")
    }
    fn walk<'a>(node: &'a serde_json::Value, hits: &mut Vec<&'a serde_json::Value>) {
        if node.get("vis_px").is_some() {
            hits.push(node);
        }
        if let Some(children) = node["children"].as_array() {
            for child in children {
                walk(child, hits);
            }
        }
    }
    #[test]
    fn clipped_child_carries_vis_px() {
        let mut host = new_host_with_wasi();
        render_fixture(&mut host, "vc_clip", 0, DEFAULT_THEME);
        let tree = parsed(&mut host);
        let mut hits = Vec::new();
        walk(&tree, &mut hits);
        let clipped: Vec<_> = hits
            .iter()
            .filter(|n| n.get("clipped").and_then(serde_json::Value::as_bool) == Some(true))
            .collect();
        assert!(
            !clipped.is_empty(),
            "vc_clip's ancestor-clipped child must carry vis_px; none found"
        );
        for node in clipped {
            let vis = node["vis_px"].as_i64().expect("vis_px is a number");
            let c = node["coords"].as_array().expect("coords");
            let total = (c[2].as_i64().unwrap() - c[0].as_i64().unwrap() + 1)
                * (c[3].as_i64().unwrap() - c[1].as_i64().unwrap() + 1);
            assert!(
                vis > 0 && vis < total,
                "partially-clipped node: 0 < vis_px({vis}) < total({total})"
            );
        }
    }
    #[test]
    fn fully_visible_tree_carries_no_vis_px() {
        let mut host = new_host_with_wasi();
        render_fixture(&mut host, "vc_fits", 0, DEFAULT_THEME);
        let tree = parsed(&mut host);
        let mut hits = Vec::new();
        walk(&tree, &mut hits);
        assert!(
            hits.is_empty(),
            "vc_fits is fully visible — no node may carry vis_px; found {}",
            hits.len()
        );
    }
}

