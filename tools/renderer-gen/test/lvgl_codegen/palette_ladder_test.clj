(defn- quantisation-hazards
  "Scan a fine OKLCH-lightness grid at one hue and chroma for coordinates where
   the UNQUANTISED luminance and the EMITTED 8-bit colour land on opposite sides
   of `floor` against `reference`. Returns both directions separately.

   :accepts-a-failure is the dangerous one - a continuum solver takes the value,
   quantises it at report time, and ships a colour under the floor.
   :rejects-a-pass is the mirror, and is a defect too: it discards emittable
   colours that do clear.

   SEARCHED, NEVER ASSERTED AT A FIXED COORDINATE. Which direction a given
   (hue, chroma, reference, floor) exhibits depends on which way the 8-bit
   rounding falls at the crossing, so a test pinned to one coordinate proves
   nothing about the next one. The first version of this test WAS pinned to one,
   and it found nothing - the hazard is real and that combination simply rounded
   the other way."
  [^double chroma ^double hue reference ^double floor]
  (let [y-ref (pl/wcag-y (pl/hex->rgb8 reference))
        hits (for [i (range 0 20001)
                   :let [l (/ (double i) 20000.0)
                         unq (pl/wcag-ratio
                              (pl/linear-rgb->wcag-y (pl/oklch->linear-rgb l chroma hue))
                              y-ref)
                         emitted (pl/realize {:oklch-l l :oklch-c chroma :oklch-h hue})
                         emr (pl/wcag-ratio (:wcag-y emitted) y-ref)]
                   :when (not= (>= unq floor) (>= emr floor))]
               {:oklch-l l :hex (:hex emitted) :reference reference :floor floor
                :unquantised-wcag-ratio unq :emitted-wcag-ratio emr})]
    {:accepts-a-failure (filter #(>= (:unquantised-wcag-ratio %) floor) hits)
     :rejects-a-pass (remove #(>= (:unquantised-wcag-ratio %) floor) hits)}))

(deftest test-the-quantisation-hazard-is-real
  (testing "the continuum and the emittable space disagree about a floor, in BOTH directions"
    (let [sweep (for [hex ["#9898B0" "#7C3AED" "#0E7490" "#F59E0B" "#10B981"]
                      reference ["#12121F" "#D0D0C0"]
                      floor [6.0 3.0]
                      :let [base (pl/hex->oklch hex)]]
                  (quantisation-hazards (:oklch-c base) (:oklch-h base) reference floor))
          accepts (mapcat :accepts-a-failure sweep)
          rejects (mapcat :rejects-a-pass sweep)]
      (is (seq accepts)
          (str "no coordinate found where the continuum ACCEPTS a colour the"
               " emitted 8-bit value fails - if this is genuinely empty the"
               " quantise-first design is unmotivated and should be revisited,"
               " not silently kept"))
      (is (seq rejects)
          "no coordinate found where the continuum rejects an emittable pass")
      (doseq [h (take 3 accepts)]
        (is (>= (:unquantised-wcag-ratio h) (:floor h)))
        (is (< (:emitted-wcag-ratio h) (:floor h)))))))

(deftest test-no-candidate-carries-the-hazard
