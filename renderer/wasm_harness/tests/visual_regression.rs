mod boundary_contracts {
    use super::*;
    use lvgl_harness::proto::ui::style_property::Value;
    /// One-label screen encoded via prost: root (bare or themed, explicit
    /// W×H) + a label at (10,10) carrying `props`.
    fn label_screen(bare: bool, props: Vec<ui::StyleProperty>) -> Vec<u8> {
        let wh = ui::StyleGroup {
            variants: vec![ui::StyleVariant {
                properties: vec![
                    ui::StyleProperty {
                        r#type: ui::StylePropertyType::PropWidth as i32,
                        value: Some(Value::UintValue(WIDTH)),
                    },
                    ui::StyleProperty {
                        r#type: ui::StylePropertyType::PropHeight as i32,
                        value: Some(Value::UintValue(HEIGHT)),
                    },
                ],
                ..Default::default()
            }],
            ..Default::default()
        };
        let label = ui::WidgetNode {
            r#type: ui::WidgetType::WidgetLabel as i32,
            uid: 1,
            x: 10,
            y: 10,
            text: "pin ABC 123".into(),
            style_groups: vec![ui::StyleGroup {
                variants: vec![ui::StyleVariant {
                    properties: props,
                    ..Default::default()
                }],
                ..Default::default()
            }],
            ..Default::default()
        };
        let root = ui::WidgetNode {
            r#type: ui::WidgetType::WidgetObj as i32,
            uid: 100,
            bare,
            children: vec![label],
            style_groups: vec![wh],
            ..Default::default()
        };
        ui::Screen {
            root: Some(root),
            ..Default::default()
        }
        .encode_to_vec()
    }
    /// Render raw Screen bytes with the pinned tick budget (the fixture
    /// renderer's twin for prost-built screens).
    fn render_bytes(host: &mut ControlsHost, pb: &[u8]) -> Vec<u8> {
        host.set_breakpoint(DEFAULT_BP).expect("set_breakpoint");
        host.set_theme_dark(DEFAULT_THEME).expect("set_theme_dark");
        host.set_dpi(DPI).expect("set_dpi");
        host.load_ui(pb).expect("load_ui");
        let mut flushed = false;
        for _ in 0..RENDER_TICKS {
            if host.tick(TICK_MS).expect("tick") {
                flushed = true;
            }
        }
        assert!(flushed, "no flush within the pinned ticks");
        host.read_framebuffer().expect("read_framebuffer")
    }
    /// A style value in the WRONG oneof slot must reject the whole load
    /// loudly (rc != 0 → host error) — the silent-skip behavior shipped
    /// three invisible styling defects from one hand-authored screen
    /// before the slot gate existed. A correct-slot load must then
    /// succeed on the same instance (no latched poison).
    #[test]
    fn wrong_oneof_slot_rejects_load() {
        let mut host = new_host();
        let bad = label_screen(
            false,
            vec![ui::StyleProperty {
                r#type: ui::StylePropertyType::PropTextColor as i32,
                value: Some(Value::UintValue(0x00FF_FFFF)),
            }],
        );
        assert!(
            host.load_ui(&bad).is_err(),
            "wrong-slot style value must reject the load"
        );
        let good = label_screen(
            false,
            vec![ui::StyleProperty {
                r#type: ui::StylePropertyType::PropTextColor as i32,
                value: Some(Value::ColorValue(ui::Color { r: 255, g: 0, b: 0 })),
            }],
        );
        host.load_ui(&good)
            .expect("correct-slot load must succeed after a rejected one");
    }
    /// Bare-root labels render the SAME full-coverage glyph pixels as under
    /// a themed root (translation-normalized: theme padding shifts content).
    /// Pins the 2026-07-19 forensic finding: the renderer is CORRECT here —
    /// an alpha-ignoring consumer made bare roots look broken, because LVGL
    /// legally leaves arbitrary color under a=0 pixels around glyph
    /// coverage. Consumers must alpha-blend; the framebuffer contract only
    /// defines color where a > 0.
    #[test]
    fn bare_root_label_glyphs_match_themed_root() {
        let color_font = || {
            vec![
                ui::StyleProperty {
                    r#type: ui::StylePropertyType::PropTextColor as i32,
                    value: Some(Value::ColorValue(ui::Color { r: 255, g: 0, b: 0 })),
                },
                ui::StyleProperty {
                    r#type: ui::StylePropertyType::PropTextFont as i32,
                    value: Some(Value::StringValue("b612mono_bold_16".into())),
                },
            ]
        };
        let glyph_set = |fb: &[u8]| -> Vec<(u32, u32)> {
            let pts: Vec<(u32, u32)> = fb
                .chunks(4)
                .enumerate()
                .filter(|(_, p)| p[0] == 255 && p[1] == 0 && p[2] == 0 && p[3] == 255)
                .map(|(i, _)| {
                    let i = u32::try_from(i).expect("pixel index fits u32");
                    (i % WIDTH, i / WIDTH)
                })
                .collect();
            let minx = pts.iter().map(|p| p.0).min().unwrap_or(0);
            let miny = pts.iter().map(|p| p.1).min().unwrap_or(0);
            pts.iter().map(|p| (p.0 - minx, p.1 - miny)).collect()
        };
        let mut bare_host = new_host_with_wasi();
        let bare = glyph_set(&render_bytes(
            &mut bare_host,
            &label_screen(true, color_font()),
        ));
        let mut themed_host = new_host_with_wasi();
        let themed = glyph_set(&render_bytes(
            &mut themed_host,
            &label_screen(false, color_font()),
        ));
        assert!(
            bare.len() > 100,
            "bare-root label rendered too few full-coverage glyph pixels: {}",
            bare.len()
        );
        assert_eq!(
            bare, themed,
            "bare vs themed root glyph pixel sets differ (translation-normalized)"
        );
    }
}
