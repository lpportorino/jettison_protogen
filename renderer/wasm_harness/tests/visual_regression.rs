    /// Build a raw ui.HostToWasm envelope with explicit (possibly invalid)
    /// pointer enum ints — the typed API can't express phase/kind = 0.
    fn raw_pointer(version: u32, phase: u64, kind: u64, t_ms: u64) -> Vec<u8> {
        fn varint(buf: &mut Vec<u8>, mut v: u64) {
            loop {
                let mut b = (v & 0x7f) as u8;
                v >>= 7;
                if v != 0 {
                    b |= 0x80;
                }
                buf.push(b);
                if v == 0 {
                    break;
                }
            }
        }
        fn key(buf: &mut Vec<u8>, field: u32, wire: u32) {
            varint(buf, u64::from((field << 3) | wire));
        }
        // inner PointerEvent body
        let mut body = Vec::new();
        key(&mut body, 1, 0);
        varint(&mut body, phase);
        key(&mut body, 2, 0);
        varint(&mut body, kind);
        key(&mut body, 3, 0);
        varint(&mut body, 1); // pointer_id
        key(&mut body, 4, 1);
        body.extend_from_slice(&0.0_f64.to_le_bytes()); // x
        key(&mut body, 5, 1);
        body.extend_from_slice(&0.0_f64.to_le_bytes()); // y
        key(&mut body, 6, 0);
        varint(&mut body, t_ms);
        // envelope
        let mut env = Vec::new();
        key(&mut env, 1, 0);
        varint(&mut env, u64::from(version));
        key(&mut env, 2, 2);
        varint(&mut env, body.len() as u64);
        env.extend_from_slice(&body);
        env
    }
