/// Render a `.pb` fixture to an RGBA framebuffer.
fn render_fixture(host: &mut ControlsHost, name: &str, bp: i32, theme: i32) -> Vec<u8> {
    render_fixture_at_dpi(host, name, bp, theme, DPI)
}
/// Render a `.pb` fixture at an explicit DPI (the dpi_invariance contract
/// is the only caller that varies it).
fn render_fixture_at_dpi(
    host: &mut ControlsHost,
    name: &str,
    bp: i32,
    theme: i32,
    dpi: i32,
) -> Vec<u8> {
    let pb_path = fixtures_dir().join(format!("{name}.pb"));
    let pb_data =
        std::fs::read(&pb_path).unwrap_or_else(|err| panic!("read {}: {err}", pb_path.display()));
    host.set_breakpoint(bp).expect("set_breakpoint failed");
    host.set_theme_dark(theme).expect("set_theme_dark failed");
    host.set_dpi(dpi).expect("set_dpi failed");
    host.load_ui(&pb_data)
        .unwrap_or_else(|err| panic!("load_ui failed for fixture '{name}': {err:?}"));
    // Exactly RENDER_TICKS ticks, matching the harness binary's pinned
    // budget (deterministic elapsed time; no adaptive settle).
    let mut flushed = false;
    for _ in 0..RENDER_TICKS {
        if host.tick(TICK_MS).expect("tick failed") {
            flushed = true;
        }
    }
    assert!(flushed, "no flush within the {RENDER_TICKS} pinned ticks");
    host.read_framebuffer().expect("read_framebuffer failed")
}
/// Render a fixture with default breakpoint and theme.
fn render(host: &mut ControlsHost, name: &str) -> Vec<u8> {
    render_fixture(host, name, DEFAULT_BP, DEFAULT_THEME)
}
/// Assert the framebuffer is not all-zero (not fully transparent).
fn assert_not_empty(label: &str, framebuffer: &[u8]) {
    let has_content = framebuffer.chunks(4).any(|pixel| pixel[3] != 0);
    assert!(has_content, "{label}: framebuffer is entirely transparent");
}
/// Assert two framebuffers are byte-identical.
fn assert_identical(label: &str, fb_a: &[u8], fb_b: &[u8]) {
    assert_eq!(fb_a.len(), fb_b.len(), "{label}: framebuffer size mismatch");
    if fb_a != fb_b {
        let pixel_count = fb_a.len() / 4;
        let diff_count = fb_a
            .chunks(4)
            .zip(fb_b.chunks(4))
            .filter(|(a, b)| a != b)
            .count();
        let ratio = diff_count as f64 / pixel_count as f64;
        panic!(
            "{label}: framebuffers differ — {diff_count}/{pixel_count} pixels ({:.2}%)",
            ratio * 100.0
        );
    }
}
/// Assert two framebuffers have at least `min_ratio` fraction of differing pixels.
fn assert_differ(label: &str, fb_a: &[u8], fb_b: &[u8], min_ratio: f64) {
    assert_eq!(fb_a.len(), fb_b.len(), "{label}: framebuffer size mismatch");
    let pixel_count = fb_a.len() / 4;
    let diff_count = fb_a
        .chunks(4)
        .zip(fb_b.chunks(4))
        .filter(|(a, b)| a != b)
        .count();
    let ratio = diff_count as f64 / pixel_count as f64;
    assert!(
        ratio >= min_ratio,
        "{label}: only {diff_count}/{pixel_count} pixels differ ({:.2}%), \
         expected at least {:.2}%",
        ratio * 100.0,
        min_ratio * 100.0
    );
}
/// Parse the live widget tree (controls_dump_tree JSON).
fn tree(host: &mut ControlsHost) -> serde_json::Value {
    let dump = host.dump_tree().expect("dump_tree");
    serde_json::from_str(&dump).expect("tree json")
}
/// Center of the first widget of `wtype` in the dumped tree — click
/// targets derive from the LIVE layout, never from hardcoded EDN coords
/// (parent padding shifts children).
fn widget_center(host: &mut ControlsHost, wtype: &str) -> (i32, i32) {
    fn find<'a>(node: &'a serde_json::Value, wtype: &str) -> Option<&'a serde_json::Value> {
        if node["type"] == wtype {
            return Some(node);
        }
        node["children"]
            .as_array()?
            .iter()
            .find_map(|child| find(child, wtype))
    }
    let root = tree(host);
    let node = find(&root, wtype).unwrap_or_else(|| panic!("no {wtype} in tree"));
    let coords = node["coords"].as_array().expect("coords");
    let value = |i: usize| coords[i].as_i64().expect("coord") as i32;
    ((value(0) + value(2)) / 2, (value(1) + value(3)) / 2)
}
// ── Px pointer driving over the R4 controls_host_message pipeline ──────────
// controls_pointer_event is gone (R4): every pointer interaction is now a
// W3C ui.PointerEvent in NDC. These px helpers convert framebuffer px ->
// NDC (the inverse of the WASM's ndc_to_px) and forward through
// controls_host_message with a monotonic event_time, so px-addressed widget
// clicks/drags keep working against the LVGL-WIDGET-owned routing branch.
// The pure-FSM gesture tests bypass these and drive NDC directly.

/// Framebuffer px -> NDC (+x right, +y UP, Y-flipped).
fn px_to_ndc(x: i32, y: i32) -> (f64, f64) {
    let ndc_x = f64::from(x) / f64::from(WIDTH) * 2.0 - 1.0;
    let ndc_y = 1.0 - f64::from(y) / f64::from(HEIGHT) * 2.0;
    (ndc_x, ndc_y)
}
// ── R5b cmd-out: decode the OPAQUE cmd.* bytes captured from host_command ──
// The renderer pre-builds the full cmd.Root (CmdSpec template + patched live
// value) and relays the bytes; the harness prost-decodes them and asserts the
// command VARIANT + field VALUES (decode-then-match, the survey's approach:
// clearer + more debuggable than a byte-template comparison). cmd.Root → its
// subsystem payload oneof → the leaf command.

use lvgl_harness::proto::cmd;
use lvgl_harness::proto::ser;
use prost::Message;
/// Decode captured `cmd.*` bytes to a top-level `cmd::Root`, fail-loud.
fn decode_cmd(bytes: &[u8]) -> cmd::Root {
    cmd::Root::decode(bytes)
        .unwrap_or_else(|e| panic!("cmd.* decode failed ({e}); {} bytes", bytes.len()))
}
/// The `RotateToNdc` leaf of a captured command, or `None` if it is a
/// different variant. Walks cmd.Root → Rotary payload → RotateToNdc.
fn as_rotate_to_ndc(bytes: &[u8]) -> Option<cmd::rotary_platform::RotateToNdc> {
    match decode_cmd(bytes).payload {
        Some(cmd::root::Payload::Rotary(r)) => match r.cmd {
            Some(cmd::rotary_platform::root::Cmd::RotateToNdc(rt)) => Some(rt),
            _ => None,
        },
        _ => None,
    }
}
