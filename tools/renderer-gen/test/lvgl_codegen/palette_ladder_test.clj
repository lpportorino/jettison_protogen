(defn- finding-for
  "The finding for one (role, mode) cell. The mode is REQUIRED: `fg-1` is
   :blocked-upstream in one mode and :reference-conflict in the other in the
   very same proposal, so a role-only lookup returns whichever sorted first and
   silently answers a different question than the one asked."
  [proposal role-key mode]
  (first (filter #(and (= role-key (:role %)) (some #{mode} (:modes %)))
                 (:findings proposal))))

(deftest test-reference-infeasible-fires-and-names-the-upstream-role
  ;; REVERT-TO-BREAK: in `solve-cell`, weaken the dead-band pre-check
  ;;   `:when (< best need)`  ->  `:when (< best 0.0)`
  ;; CONTROL: test-unreachable-in-gamut-is-a-different-status must stay GREEN.
  ;; Under the mutation accent-text falls through to the search, finds nothing,
  ;; and is misreported as :unreachable-in-gamut — a status whose fix is this
  ;; role's own hue and chroma, which is precisely the wrong instruction.
  (testing "a foreground on a dead-band fill is refused BEFORE any search, against the fill"
    (let [f (finding-for dead-band-pinned-proposal :accent-text :dark)]
      (is (some? f) "accent-text produced no finding at all against a pinned accent-bg")
      (is (= :reference-infeasible (:status f))
          (str "accent-text is " (pr-str (:status f))
               " — the fix that status implies belongs to the wrong role"))
      (is (= #{:accent-bg} (set (map :reference (:infeasible-references f))))
          "the finding does not name accent-bg as the role that must move")
      (doseq [r (:infeasible-references f)]
        (is (< (double (:max-hostable-wcag-ratio r)) (double (:floor-ratio r)))
            "the reported bound does not actually fall short of the floor")
        (is (some? (:reference-must-reach r))
            "the finding states the problem without stating the repair band")))))

(deftest test-the-dependency-axis-repairs-what-pinning-dooms
  ;; The DISCRIMINATOR for the test above: the same role, the same hue, the same
  ;; chroma budget, and a different verdict — so the :reference-infeasible above
  ;; is attributable to accent-bg's pinned VALUE and to nothing about accent-text.
  (testing "unpinning the fill makes the doomed foreground solvable"
    (is (nil? (finding-for dead-band-free-proposal :accent-text :dark))
        "accent-text still fails when accent-bg is free to move")
    (is (contains? (:palette dead-band-free-proposal) [:accent-text :dark]))
    (is (not= (get-in dead-band-free-proposal [:palette [:accent-bg :dark] :hex])
              (get-in dead-band-pinned-proposal [:palette [:accent-bg :dark] :hex]))
        "accent-bg did not move, so the two runs do not differ in the way claimed")))

(deftest test-blocked-upstream-is-emitted-not-skipped
  ;; DISCRIMINATOR, no mutation needed: fg-1/dark is :blocked-upstream in the
  ;; full graph and :reference-conflict once the status fills are dropped. Same
  ;; role, same constraints on itself — so the blocked status is caused by the
  ;; upstream failure and not by fg-1.
