   Deliberately spread across the range: the two accent rows are the ones the
   derivation's central claim depends on, and the 1.76 row is the worst cell in
   the shipped palette."
  [["#E8E8F0" "#12121F" 15.22]
   ["#E8E8F0" "#7C3AED" 4.68]
   ["#9A9BB6" "#1E1E2E" 6.04]
   ["#E8E8F0" "#F59E0B" 1.76]
