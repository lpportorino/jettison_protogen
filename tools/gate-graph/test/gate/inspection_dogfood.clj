(ns gate.inspection-dogfood
  "Acceptance exercise of the inspection APIs on two actual public dogfood captures."
  (:require [gate.admission :as admission]
            [gate.canonical :as canonical]
            [gate.contract :as c]
            [gate.diagnostic :as diagnostic]
            [gate.diff :as diff]
            [gate.graph :as graph]
            [gate.measure :as measure]
            [gate.query :as query]
            [gate.schema :as schema]
            [malli.core :as m])
  (:import [java.nio.file Files Path]
           [java.nio.file.attribute FileAttribute]))

(def PathText [:string {:min 1 :max 4096}])
(def Check [:enum :complete-input :gate-page :pagination :children :owned-measurements
            :concurrent-window :rss-extremum :rss-sum-refusal :cpu-overlap-refusal :comparison])
(def ^:private budget {:visits 128000 :rows 100 :bytes 1048576})
(def ^:private aggregate-budget {:pairs 100 :bytes 65536})

(defn- require-check!
  "Fail with a stable named acceptance check, not a printed pass claim or raw private input."
  [check value]
  (when-not value (throw (ex-info "Inspection dogfood failed" {:code :inspection-dogfood-failed :check check}))))
(m/=> require-check! [:=> [:cat Check :boolean] :nil])

(defn- load-owned-graph
  "Read a quiescent artifact generated by this checkout, then apply bounded EDN admission.
   This test harness assumes trusted filesystem ownership; production stream adapters remain separate."
  [path]
  (when (> (Files/size (Path/of path (make-array String 0))) 134217728)
    (throw (ex-info "Dogfood artifact too large" {:code :input-byte-limit})))
  (admission/decode (slurp path :encoding "UTF-8") :graph admission/default-limits))
(m/=> load-owned-graph [:=> [:cat PathText] c/Graph])

(defn- save!
  "Persist the same canonical result an LLM client receives; no human-only summary replaces it."
  [directory artifact-name value]
  (spit (str directory "/" artifact-name ".edn") (str (canonical/encode value 1048576) "\n") :encoding "UTF-8"))
(m/=> save! [:=> [:cat PathText c/Id schema/Encodable] :nil])

(defn -main
  "Exercise drill, continuation, temporal coincidence, aggregation and diff against two real public runs.
   Arguments are BEFORE-EDN AFTER-EDN NEW-OUTPUT-DIRECTORY. Both inputs must be complete scoped
   dogfood runs with two concurrent gate suites and wait4 CPU/RSS observations. Outputs preserve
   exact API responses, including overlap/RSS refusals. Temporal coincidence never asserts causality."
  [before-path after-path output]
  (diagnostic/install!)
  (let [before (load-owned-graph before-path) after (load-owned-graph after-path)
        context (query/prepare after)
        gates (query/page context {:select {:op :nodes :where {:kind :gate}} :budget budget})
        gate (first (:rows gates))
        first-page (query/page context {:select {:op :nodes :where {:kind :gate}} :budget (assoc budget :rows 1)})
        second-page (query/page context {:select {:op :nodes :where {:kind :gate}} :budget budget :cursor (:next first-page)})
        children (query/page context {:select {:op :children :anchor (:parent gate)} :budget budget})
        owned (query/page context {:select {:op :measurements :where {:node (:id gate)}} :budget budget})
        coincident (query/page context {:select {:op :window :interval (:interval gate) :where {:kind :gate}} :budget budget})
        rss (query/page context {:select {:op :measurements :where {:quantity :rss-peak-bytes}} :budget budget})
        cpu (query/page context {:select {:op :measurements :where {:quantity :cpu-user-ns}} :budget budget})
        extrema (measure/aggregate context {:op :maximum-observation :measurements (mapv :id (:rows rss)) :budget aggregate-budget})
        rss-sum (measure/aggregate context {:op :sum :measurements (mapv :id (:rows rss)) :budget aggregate-budget})
        cpu-sum (measure/aggregate context {:op :sum :measurements (mapv :id (:rows cpu)) :budget aggregate-budget})
        comparison (diff/page (diff/prepare (query/prepare before) context) {:select {:op :tasks :changed-only? false} :budget budget})]
    (require-check! :complete-input (and (get-in before [:run :complete?]) (get-in after [:run :complete?])))
    (require-check! :gate-page (and (= :complete (:stop gates)) (= 2 (count (:rows gates)))))
    (require-check! :pagination (and (= :row-limit (:stop first-page)) (= :complete (:stop second-page))
                                     (= (:rows gates) (into (:rows first-page) (:rows second-page)))))
    (require-check! :children (= (set (map :id (:rows gates))) (set (map :id (:rows children)))))
    (require-check! :owned-measurements (and (= :complete (:stop owned)) (= 3 (count (:rows owned)))
                                             (every? #(= (:id gate) (:node %)) (:rows owned))))
    (require-check! :concurrent-window (= 2 (count (:rows coincident))))
    (require-check! :rss-extremum (and (= :complete (:status extrema)) (= :observation-extremum (:basis extrema))))
    (require-check! :rss-sum-refusal (and (= :refused (:status rss-sum)) (= :unsupported-form (:code rss-sum))))
    (require-check! :cpu-overlap-refusal (and (= :refused (:status cpu-sum)) (= :overlap-unproven (:code cpu-sum))))
    (require-check! :comparison
                    (and (= :complete (:stop comparison))
                         (= (set (map #(select-keys % [:kind :key]) (concat (:nodes before) (:nodes after))))
                            (set (map :identity (:rows comparison))))))
    (graph/require-valid! after)
    (Files/createDirectory (Path/of output (make-array String 0)) (make-array FileAttribute 0))
    (doseq [[artifact-name result] [["gates" gates] ["first-page" first-page] ["second-page" second-page]
                                    ["children" children] ["owned-measurements" owned] ["coincident-tasks" coincident]
                                    ["rss-maximum" extrema] ["rss-sum-refusal" rss-sum] ["cpu-overlap-refusal" cpu-sum]
                                    ["comparison" comparison]]]
      (save! output artifact-name result))
    (prn {:status :passed :checks 10 :artifact (:artifact context)}))
  (shutdown-agents))
(m/=> -main [:=> [:cat PathText PathText PathText] :nil])
